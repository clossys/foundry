#!/usr/bin/env node
/**
 * Copies the shared Advisor plan contract, and a byte-identical copy of the
 * one contract checker implementation, into this package at build time
 * (issue #1586): so @clossys/writer reads an Advisor plan record against the
 * same `docs/contracts/advisor-plan.json` that every other reader of a plan
 * validates against, with no runtime dependency on any other package.
 *
 * Follows `packages/starter/scripts/pack-ledger-contract.mjs` -- see that
 * file and `scripts/lib/plan-contracts.mjs`, whose
 * `renderContractSchemaCopy()` this reuses for a byte-identical checker
 * copy. It does not call that library's `renderPlanContractsModule()`,
 * which refuses any file list but its own fixed one. `advisor-plan.json`
 * refers to no other contract file, so the loader this package gives the
 * checker refuses every name.
 *
 * `src/generated/` is gitignored, like every other packed build output in
 * this repository.
 */
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { renderContractSchemaCopy } from "../../../scripts/lib/plan-contracts.mjs";

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = join(packageRoot, "..", "..");

const PLAN_CONTRACT_FILE = "advisor-plan.json";
export const PLAN_CONTRACT_MODULE_PATH = "src/generated/advisor-plan-contract.generated.ts";
export const CONTRACT_SCHEMA_COPY_PATH = "src/generated/contract-schema.generated.ts";

/** The generated data module's source text: the packed plan contract, parsed and re-serialized. */
function renderPlanContractModule() {
  const contract = JSON.parse(readFileSync(join(repoRoot, "docs", "contracts", PLAN_CONTRACT_FILE), "utf8"));
  return `// AUTO-GENERATED by this package's build-time packer (issue #1586).
// Do not edit by hand -- edits are overwritten on the next \`npm run build\`.
// Source of truth: the shared Advisor plan contract in this package's source
// repository (not shipped in this package). Every package that validates a
// plan packs this same contract.

/** The shared Advisor plan contract (${PLAN_CONTRACT_FILE}) this package validates against. */
export const ADVISOR_PLAN_CONTRACT: Readonly<Record<string, unknown>> = ${JSON.stringify(contract, null, 2)};
`;
}

const generatedDir = join(packageRoot, "src", "generated");
if (existsSync(generatedDir)) rmSync(generatedDir, { recursive: true, force: true });
mkdirSync(generatedDir, { recursive: true });
writeFileSync(join(packageRoot, PLAN_CONTRACT_MODULE_PATH), renderPlanContractModule());
writeFileSync(join(packageRoot, CONTRACT_SCHEMA_COPY_PATH), renderContractSchemaCopy(repoRoot));
console.log("pack-plan-contract: wrote the plan contract and the contract checker copy into src/generated/");
