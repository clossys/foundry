/**
 * The constitution delta gate (W2-G run 2, W2-G3; slot-constitution.md W2-G, "--strict after E2").
 *
 * Until E2 the chain's `constitution` step (`clossys check --constitution --enforced`) blocks on new
 * findings, not on the whole set (W2-G3 G1). An enforced finding blocks when its key is not in the
 * last green report (more rows under a key than the report counted): a new finding. The gate also
 * blocks on a green report that fails its integrity check (hand-edited, digest mismatch, malformed).
 * Findings about a record that changed since the last green report, or about one of that record's
 * R07 dependants (slots whose slot.json `inputs` ∪ `uses` reach it, transitively), are counted and
 * printed as the changed-record count, never blocking: a mechanical edit to a record does not have
 * to fix every pre-existing finding on it. A green key the run no longer produces is stale: listed,
 * never blocking (W2-G3 G2). The whole set is still reported; nothing is suppressed and no rule's
 * level changes. `--strict` is the full gate: every enforced finding blocks.
 * TODO(E2): make the full gate the default for `--enforced` and retire this delta (E2 "enforce":
 * every rule row enforced, the chain step runs `--strict`).
 *
 * The last green report lives at `<P>/pipeline/constitution-green.json` (P = packages/producer),
 * reviewed with the code. Only `clossys check --constitution --record-green` with no `--rule` or
 * `--agent` writes it, and only to shrink it: with a report in place, the new report may drop keys
 * or lower counts (fixed findings) but never add a key or raise a count (seedGrowth); a run with a
 * new finding is refused. With no report yet it seeds one (the bootstrap). The report is generated,
 * never hand-edited: it carries a digest over its own content, and every run fails while the digest
 * does not match.
 *
 * A key is (check, subject): `<check> <agent>/<slot> <path>`, the path shortened to the part inside
 * the slot folder (`.` for the folder itself), plus `#<candidate>` when the path does not name it. The reason text is not part
 * of the key (some reasons carry tool output); several rows under one key are counted.
 * A key never embeds a line number (W2-G2 D2): a row whose path cites `<file>:<line>[:<col>]` (the
 * code rules R11 and R13 cite the line of the code they judge) is keyed by the file plus
 * `@<anchor>`, a hash of its whitespace-normalised reason. For those rows the reason is the rule's
 * fixed text and the judged snippet (R11.1: the call; R13: the detail or message), so the key
 * follows the code, not its line: a line shift above it keeps the key, a change to the snippet
 * makes it a new key. Two rows of one file with the same snippet share a key (counted).
 *
 * A record's digest leaves out exactly the slot.json fields the `ia` verb's position bookkeeping
 * rewrites (W2-G2 D1; POSITION_FIELDS), and the `ia-position` ledger events that record those
 * rewrites (R14.1: the `ia` verb appends one event per file it writes, IA_POSITION_KIND when only
 * POSITION_FIELDS changed): an order-only renumber of later slots by `clossys ia --contract
 * --under`, `--remove` or a regroup does not change those slots' records. Every other byte of the
 * record counts, every other ledger event included.
 */
import { createHash } from "node:crypto";
import { existsSync, readFileSync } from "node:fs";
import { mkdir, rename, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { dependencySet, isObject } from "./checks/shared.js";
import type { ConstitutionContext, JsonRecord, Row } from "./types.js";

export const GREEN_SCHEMA = "clossys.constitution-green/1";
/** `<P>/pipeline/constitution-green.json`, resolved from this module (src/ or dist/ alike). */
export const DEFAULT_GREEN_PATH = fileURLToPath(new URL("../../pipeline/constitution-green.json", import.meta.url));
export const GREEN_NOTE = "Generated by `clossys check --constitution --record-green` (a green full run); never edit by hand: the digest and the stale-key check fail an edited file.";

/** Per-record content digests and the R07 dependency set of every slot record, from one context. */
export interface RecordIndex {
  /** `<agent>/<slot>` for a slot folder, `<agent>` for the agent folder's own records (ia.json, retired/). */
  readonly digests: Readonly<Record<string, string>>;
  /** Slot record id → the slot ids its slot.json `inputs` ∪ `uses` name. */
  readonly dependsOn: Readonly<Record<string, readonly string[]>>;
}

export interface GreenReport {
  readonly schema: typeof GREEN_SCHEMA;
  readonly note: string;
  /** The workspace's root package.json name; a report from another workspace does not apply. */
  readonly workspace: string;
  /** The commit the report was recorded at (`git rev-parse HEAD` of the workspace root). */
  readonly commit: string;
  /** Enforced findings recorded (the sum of the key counts). */
  readonly enforced: number;
  readonly keys: Readonly<Record<string, number>>;
  readonly records: Readonly<Record<string, string>>;
  /** sha256 of the canonical JSON of every other field. */
  readonly digest: string;
}

export interface DeltaScope {
  /** The rules the run covered (a green key outside them is not judged stale). */
  readonly rules: readonly string[];
  /** The agent the run was narrowed to, if any. */
  readonly agent?: string;
}

export interface Delta {
  /** Why no green report applies (missing, another workspace, unreadable); every enforced finding is then new. */
  readonly baseline?: string;
  /** Integrity failures of the green report (digest mismatch, malformed). */
  readonly tampered: readonly string[];
  /** Green keys the run no longer produces as often as recorded, with the counts. */
  readonly stale: readonly { key: string; recorded: number; produced: number }[];
  readonly total: number;
  readonly pending: number;
  readonly enforced: number;
  /** Enforced rows that block: new findings, whose key is not (or not that often) in the green report. */
  readonly blocking: readonly Row[];
  /** The blocking rows' count (blocking.length). */
  readonly newRows: number;
  /** Enforced rows about a changed record or its R07 dependant, new or not: counted, never blocking on their own. */
  readonly changedRows: number;
  /** Records changed since the green report (digest differs or new), and their dependants. */
  readonly changedRecords: readonly string[];
  readonly dependantRecords: readonly string[];
  /** The gate verdict: no new finding and an intact report (stale keys and changed records do not block). */
  readonly ok: boolean;
}

const sha256 = (text: string) => createHash("sha256").update(text).digest("hex");

/** Canonical JSON: object keys sorted at every level. */
export function canonical(value: unknown): string {
  if (Array.isArray(value)) return `[${value.map(canonical).join(",")}]`;
  if (value !== null && typeof value === "object") {
    return `{${Object.keys(value).sort().map(key => `${JSON.stringify(key)}:${canonical((value as Record<string, unknown>)[key])}`).join(",")}}`;
  }
  return JSON.stringify(value);
}

/** A path that cites a line: `<file>:<line>` or `<file>:<line>:<col>` (the file has an extension, no space). */
const LINE_CITED = /^([^\s:]+\.[A-Za-z0-9]+):\d+(?::\d+)?$/;

/** The content anchor of a line-cited row: a hash of its whitespace-normalised reason (see the module note). */
export function rowAnchor(row: Row): string {
  return sha256(row.reason.replace(/\s+/g, " ").trim()).slice(0, 12);
}

/** The finding's key: (check, subject). Never a line number: a line-cited path keys by file and content anchor. */
export function rowKey(row: Row): string {
  const cited = LINE_CITED.exec(row.path);
  const rowPath = cited ? cited[1]! : row.path;
  const dir = `agents/${row.agent}/${row.slot}`;
  const at = rowPath.indexOf(`${dir}/`);
  const path = rowPath === dir || rowPath.endsWith(`/${dir}`) ? "." : at >= 0 && (at === 0 || rowPath[at - 1] === "/") ? rowPath.slice(at + dir.length + 1) : rowPath;
  const candidate = row.candidate && !path.endsWith(row.candidate) ? ` #${row.candidate}` : "";
  const anchor = cited ? ` @${rowAnchor(row)}` : "";
  return `${row.check} ${row.agent}/${row.slot} ${path}${candidate}${anchor}`;
}

/**
 * The slot.json fields the `ia` verb's position bookkeeping rewrites: followPositions in
 * cli/ia-regroup.ts writes a slot's `ia` as its slotPositions entry `{ l0?, l1, l2, order }`, and an
 * order-only renumber of later slots changes `ia.order` alone. Named one by one; nothing else of
 * slot.json is left out of a record's digest (ledgerRecordView leaves out the events recording them).
 */
export const POSITION_FIELDS = ["ia.l0", "ia.l1", "ia.l2", "ia.order"] as const;

/**
 * The slot.json bytes a record digest covers: the file without POSITION_FIELDS. Only a slot.json in
 * the bytes the slot writer produces (2-space JSON and a newline, records/slot-model jsonBytes) is
 * normalised; any other file (unparsed, not an object, other formatting) is digested as it is, so a
 * change the view could not see still counts.
 */
export function slotRecordView(record: JsonRecord | undefined): string | null {
  if (!record) return null;
  const value = record.value;
  if (!isObject(value) || `${JSON.stringify(value, null, 2)}\n` !== record.text) return record.text;
  const view: Record<string, unknown> = { ...value };
  for (const field of POSITION_FIELDS) {
    const [parent, key] = field.split(".") as [string, string];
    const holder = view[parent];
    if (!isObject(holder) || !(key in holder)) continue;
    const { [key]: _position, ...rest } = holder;
    view[parent] = rest;
  }
  return `${JSON.stringify(view, null, 2)}\n`;
}

/** The ledger event kind of an `ia` verb write that changed only POSITION_FIELDS (an order-only renumber). */
export const IA_POSITION_KIND = "ia-position";
/** The ledger event kind of every other `ia` verb write. */
export const IA_KIND = "ia";

/**
 * The kind of the ledger event an `ia` verb write of a slot.json carries: IA_POSITION_KIND when the
 * file existed and its record view (slotRecordView, the digest's own view) is unchanged, so only
 * POSITION_FIELDS moved; IA_KIND otherwise (a new file, any other field, unnormalised bytes).
 */
export function slotWriteKind(before: string | null, after: string): typeof IA_POSITION_KIND | typeof IA_KIND {
  if (before === null || before === after) return IA_KIND;
  const view = (text: string) => { try { return slotRecordView({ path: "slot.json", text, value: JSON.parse(text) as unknown }); } catch { return text; } };
  const was = view(before), now = view(after);
  // Both files normalised (the view differs from the bytes) and equal without POSITION_FIELDS.
  return was === now && was !== before && now !== after ? IA_POSITION_KIND : IA_KIND;
}

/** An `ia-position` event: a slot `slot` event of the `ia` verb, kind IA_POSITION_KIND, recording slot.json alone. */
export function isIaPositionEvent(event: unknown): boolean {
  if (!isObject(event) || event.op !== "slot" || event.verb !== "ia" || event.kind !== IA_POSITION_KIND) return false;
  const records = event.records;
  return Array.isArray(records) && records.length === 1 && isObject(records[0]) && records[0].file === "slot.json";
}

/**
 * The ledger.json bytes a record digest covers: the file without its `ia-position` events (D1). Only
 * a ledger in the bytes the ledger writer produces (2-space JSON and a newline) is normalised; any
 * other file is digested as it is, and a ledger with no such event is its bytes unchanged.
 */
export function ledgerRecordView(record: JsonRecord | undefined): string | null {
  if (!record) return null;
  const value = record.value;
  if (!isObject(value) || !Array.isArray(value.events) || `${JSON.stringify(value, null, 2)}\n` !== record.text) return record.text;
  const events = value.events.filter(event => !isIaPositionEvent(event));
  if (events.length === value.events.length) return record.text;
  return `${JSON.stringify({ ...value, events }, null, 2)}\n`;
}

/** The record a row is about: its slot folder, else its agent folder, else none (`*` rows). */
export function rowRecord(row: Row, digests: Readonly<Record<string, string>>): string | undefined {
  if (row.agent === "*") return undefined;
  const slot = `${row.agent}/${row.slot}`;
  return slot in digests ? slot : row.agent in digests ? row.agent : undefined;
}

/** Content digests of every slot folder and agent folder, and each slot's dependency set. */
export function recordIndex(ctx: ConstitutionContext): RecordIndex {
  const digests: Record<string, string> = {};
  const dependsOn: Record<string, string[]> = {};
  for (const agent of ctx.agents) {
    digests[agent.agent] = sha256(canonical({ ia: agent.ia?.text ?? null, entries: agent.entries, retired: agent.retired.map(item => [item.name, item.sha256]) })).slice(0, 16);
    for (const slot of agent.slots.values()) {
      const id = `${agent.agent}/${slot.id}`;
      digests[id] = sha256(canonical({
        live: slot.live, entries: slot.entries, slot: slotRecordView(slot.slot), pin: slot.pin?.text ?? null, ledger: ledgerRecordView(slot.ledger),
        candidates: slot.candidates.map(item => [item.name, item.sha256]), retired: slot.retired.map(item => [item.name, item.sha256]),
      })).slice(0, 16);
      const deps = dependencySet(slot);
      if (deps?.size) dependsOn[id] = [...deps].sort();
    }
  }
  return { digests: sort(digests), dependsOn: sort(dependsOn) };
}

function sort<T>(record: Record<string, T>): Record<string, T> {
  return Object.fromEntries(Object.entries(record).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
}

function keyCounts(rows: readonly Row[]): Record<string, number> {
  const counts: Record<string, number> = {};
  for (const row of rows) if (!row.pending) counts[rowKey(row)] = (counts[rowKey(row)] ?? 0) + 1;
  return sort(counts);
}

/** The digest a green report must carry: over every field but `digest`. */
export function greenDigest(report: Omit<GreenReport, "digest"> & { digest?: unknown }): string {
  const { digest: _digest, ...rest } = report;
  return sha256(canonical(rest));
}

/** A green report of this run's rows and records. */
export function buildGreen(rows: readonly Row[], index: RecordIndex, meta: { workspace: string; commit: string }): GreenReport {
  const keys = keyCounts(rows);
  const body = {
    schema: GREEN_SCHEMA, note: GREEN_NOTE, workspace: meta.workspace, commit: meta.commit,
    enforced: Object.values(keys).reduce((sum, count) => sum + count, 0), keys, records: index.digests,
  } as const;
  return { ...body, digest: greenDigest(body) };
}

/** Integrity problems of a parsed green report; empty when it is intact. */
export function verifyGreen(value: unknown): string[] {
  if (value === null || typeof value !== "object" || Array.isArray(value)) return ["the green report is not a JSON object"];
  const doc = value as Record<string, unknown>;
  const problems: string[] = [];
  if (doc.schema !== GREEN_SCHEMA) problems.push(`schema is ${JSON.stringify(doc.schema)}, not ${GREEN_SCHEMA}`);
  for (const field of ["keys", "records"] as const) {
    const map = doc[field];
    if (map === null || typeof map !== "object" || Array.isArray(map)) problems.push(`${field} is not an object`);
    else if (field === "keys" && !Object.values(map).every(count => Number.isInteger(count) && (count as number) > 0)) problems.push("a key count is not a positive integer");
  }
  if (typeof doc.digest !== "string") problems.push("digest is missing");
  else if (doc.digest !== greenDigest(doc as unknown as GreenReport)) problems.push("digest does not match the content (the report was edited by hand; re-record it with --record-green)");
  return problems;
}

export type GreenRead = { readonly report?: GreenReport; readonly baseline?: string; readonly tampered: readonly string[] };

/** Reads the green report at `path` for this workspace. */
export function readGreen(path: string, workspace: string): GreenRead {
  if (!existsSync(path)) return { baseline: `no green report at ${path}`, tampered: [] };
  let value: unknown;
  try { value = JSON.parse(readFileSync(path, "utf8")); }
  catch (error) { return { baseline: `green report ${path} is unreadable`, tampered: [`not JSON: ${(error as Error).message}`] }; }
  const tampered = verifyGreen(value);
  if (tampered.length) return { baseline: `green report ${path} failed its integrity check`, tampered };
  const report = value as GreenReport;
  if (report.workspace !== workspace) return { baseline: `green report ${path} is for workspace ${JSON.stringify(report.workspace)}, not ${JSON.stringify(workspace)}`, tampered: [] };
  return { report, tampered: [] };
}

/** Writes the report atomically, one key per line. */
export async function writeGreen(path: string, report: GreenReport): Promise<void> {
  await mkdir(dirname(path), { recursive: true });
  const temp = join(dirname(path), `.constitution-green.${process.pid}.tmp`);
  await writeFile(temp, `${JSON.stringify(report, null, 2)}\n`, "utf8");
  await rename(temp, path);
}

/** The records changed since the green report, and every slot record that depends on one (transitively). */
export function changedRecords(index: RecordIndex, green: Pick<GreenReport, "records">): { changed: Set<string>; dependants: Set<string> } {
  const changed = new Set(Object.keys(index.digests).filter(id => green.records[id] !== index.digests[id]));
  // slot id → the slot records that name it in inputs ∪ uses.
  const users = new Map<string, string[]>();
  for (const [record, deps] of Object.entries(index.dependsOn)) for (const dep of deps) users.set(dep, [...(users.get(dep) ?? []), record]);
  const slotId = (record: string) => record.includes("/") ? record.slice(record.indexOf("/") + 1) : undefined;
  const dependants = new Set<string>();
  const queue = [...changed];
  while (queue.length) {
    const id = slotId(queue.shift()!);
    if (!id) continue;
    for (const user of users.get(id) ?? []) {
      if (changed.has(user) || dependants.has(user)) continue;
      dependants.add(user);
      queue.push(user);
    }
  }
  return { changed, dependants };
}

/**
 * The delta of this run against the green report: which enforced rows block under (a) or (b),
 * which green keys are stale (within the run's scope), and whether the report is intact.
 */
export function evaluateDelta(rows: readonly Row[], index: RecordIndex, read: GreenRead, scope: DeltaScope): Delta {
  const enforcedRows = rows.filter(row => !row.pending);
  const base = { total: rows.length, pending: rows.length - enforcedRows.length, enforced: enforcedRows.length, tampered: read.tampered };
  if (!read.report) {
    return { ...base, ...(read.baseline ? { baseline: read.baseline } : {}), stale: [], blocking: enforcedRows, newRows: enforcedRows.length, changedRows: 0, changedRecords: [], dependantRecords: [], ok: enforcedRows.length === 0 && read.tampered.length === 0 };
  }
  const green = read.report;
  const { changed, dependants } = changedRecords(index, green);
  const seen: Record<string, number> = {};
  const blocking: Row[] = [];
  let newRows = 0, changedRows = 0;
  for (const row of enforcedRows) {
    const key = rowKey(row);
    seen[key] = (seen[key] ?? 0) + 1;
    const isNew = seen[key]! > (green.keys[key] ?? 0);
    const record = rowRecord(row, index.digests);
    const onChanged = record !== undefined && (changed.has(record) || dependants.has(record));
    if (onChanged) changedRows++;
    if (isNew) { newRows++; blocking.push(row); }
  }
  const rules = new Set(scope.rules);
  const inScope = (key: string) => {
    const check = key.slice(0, key.indexOf(" "));
    const agent = key.slice(key.indexOf(" ") + 1).split("/")[0];
    return rules.has(check.split(".")[0]!) && (!scope.agent || agent === scope.agent || agent === "*");
  };
  const stale = Object.entries(green.keys)
    .filter(([key, recorded]) => inScope(key) && (seen[key] ?? 0) < recorded)
    .map(([key, recorded]) => ({ key, recorded, produced: seen[key] ?? 0 }));
  return {
    ...base, stale, blocking, newRows, changedRows,
    changedRecords: [...changed].sort(), dependantRecords: [...dependants].sort(),
    ok: blocking.length === 0 && read.tampered.length === 0,
  };
}

/**
 * What a re-record would add to the green report: every key of `next` that `old` lacks, or counts
 * more often. `--record-green` over an existing report writes only when this is empty, so a
 * re-record only drops fixed findings (removals and lowered counts) and never admits a new one.
 */
export function seedGrowth(old: Pick<GreenReport, "keys">, next: Pick<GreenReport, "keys">): { key: string; recorded: number; produced: number }[] {
  return Object.entries(next.keys)
    .filter(([key, count]) => count > (old.keys[key] ?? 0))
    .map(([key, produced]) => ({ key, recorded: old.keys[key] ?? 0, produced }));
}

/** The two counts every run prints (delta and total), and why the gate passes or fails. */
export function formatDelta(delta: Delta, mode: "enforced" | "strict" | "report"): string {
  const lines: string[] = [];
  const counts = `new ${delta.newRows}, changed-record ${delta.changedRows} (not blocking until E2), stale ${delta.stale.length} (not blocking) of enforced ${delta.enforced}; total rows ${delta.total} (pending ${delta.pending}, listed, not blocking)`;
  const records = delta.changedRecords.length || delta.dependantRecords.length ? `; changed records ${delta.changedRecords.length} (+${delta.dependantRecords.length} R07 dependants)` : "";
  if (mode === "strict") {
    lines.push(`constitution --strict (full gate): ${delta.enforced || delta.tampered.length ? "FAIL" : "PASS"}  enforced findings ${delta.enforced} block; ${counts}`);
  } else if (mode === "enforced") {
    lines.push(`constitution --enforced (delta gate until E2): ${delta.ok ? "PASS" : "FAIL"}  ${counts}${records}`);
  } else {
    lines.push(`constitution delta: ${counts}${records}`);
  }
  if (delta.baseline) lines.push(`  baseline: ${delta.baseline}; every enforced finding counts as new (seed it with --record-green)`);
  for (const problem of delta.tampered) lines.push(`  green report: ${problem}`);
  if (delta.stale.length) {
    lines.push(`  green report: ${delta.stale.length} key(s) no longer produced as recorded (not blocking); --record-green drops them when no finding is new:`);
    for (const item of delta.stale.slice(0, 20)) lines.push(`    ${item.key}  (recorded ${item.recorded}, produced ${item.produced})`);
    if (delta.stale.length > 20) lines.push(`    ... ${delta.stale.length - 20} more`);
  }
  if (mode === "enforced" && delta.blocking.length) {
    lines.push("  blocking:");
    for (const row of delta.blocking.slice(0, 50)) lines.push(`    ${rowKey(row)}: ${row.reason}`);
    if (delta.blocking.length > 50) lines.push(`    ... ${delta.blocking.length - 50} more (--json lists every row)`);
  }
  return lines.join("\n");
}
