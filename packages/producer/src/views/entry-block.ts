/**
 * The managed entry block the skills install (`clossys init`, init-skills.ts) writes into the consumer's `AGENTS.md`
 * (foundry-build-0048 CP1-FRONTDOOR). It is opt-in, not a takeover: it never tells every session to act as Producer.
 * It says three things only:
 *   (a) the covered scope, generated from the installed agents (their skills) and the workspace's records (each agent's
 *       IA groups and the Publisher releases), so it grows with coverage and is never hand-written;
 *   (b) use the `clossys-producer` skill when the owner invokes it or asks for covered work; anything else is ordinary
 *       work in the repository;
 *   (c) records under `clossys/` and Clossys-generated output change only through `clossys` verbs, in any session.
 * Only the text between the two markers is managed: the file is created when absent, text outside the markers is
 * never touched, and a second install on the same inputs writes the same bytes.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { readIa } from "../records/slots.js";
import { SLOT_AGENTS, type IaDoc, type SlotAgent } from "../records/slot-model/index.js";
import { skillRoles } from "../cli/init-skills.js";

export const ENTRY_START = "<!-- clossys:entry -->";
export const ENTRY_END = "<!-- /clossys:entry -->";

const title = (agent: string) => agent.charAt(0).toUpperCase() + agent.slice(1);

/** An agent's IA top-level group labels, in IA order; none while the workspace holds no IA for it. */
const groupsOf = (ia: IaDoc | null): string[] => ia ? [...new Set(ia.nodes.map(node => node.label))] : [];

/** The Publisher releases the workspace IA places (`release.<publication>`), by publication, in IA order. */
const releasesOf = (ia: IaDoc | null): string[] => ia
  ? ia.nodes.flatMap(node => node.children.flatMap(child => child.slots)).filter(slot => slot.startsWith("release.")).map(slot => slot.slice("release.".length))
  : [];

/**
 * The covered scope, one line per covered area: each installed agent (a `@clossys/<agent>` package that ships a
 * skill) with its workspace IA groups, then the Publisher releases. Generated from the install and the records only.
 */
export function coveredScope(root: string): string[] {
  const consumer = join(root, "clossys");
  const installed = new Set(skillRoles(root).map(item => item.role));
  const agents = (SLOT_AGENTS as readonly SlotAgent[]).filter(agent => installed.has(agent));
  const lines: string[] = [];
  for (const agent of agents) {
    const ia = existsSync(consumer) ? readIa(consumer, agent) : null;
    const groups = groupsOf(ia);
    lines.push(`${title(agent)} (\`@clossys-${agent}\`)${groups.length ? `: ${groups.join(", ")}` : ""}`);
    if (agent === "publisher") {
      const releases = releasesOf(ia);
      if (releases.length) lines.push(`Publisher releases: ${releases.join(", ")}`);
    }
  }
  return lines;
}

/** The block's bytes for a scope list, markers included (no trailing newline). */
export function entryBlock(scope: readonly string[]): string {
  return [
    ENTRY_START,
    "## Clossys",
    "",
    "Clossys covers this work in this repository (generated by `clossys init` from the installed agents and the workspace records):",
    ...scope.map(line => `- ${line}`),
    "",
    "Use the `clossys-producer` skill only when the owner invokes it (`@clossys-producer`, or \"clossys ...\") or asks for covered work. Everything else is ordinary work in this repository.",
    "",
    "In any session, records under `clossys/` and Clossys-generated output change only through `clossys` verbs. Never edit them by hand.",
    ENTRY_END,
  ].join("\n");
}

export interface EntryBlockResult {
  readonly file: string;
  /**
   * "added" when the block was appended, "updated" when the managed text changed, "present" when the bytes were already
   * right, "none" when no Clossys agent is installed (nothing is covered, so nothing is written).
   */
  readonly outcome: "added" | "updated" | "present" | "none";
}

/**
 * Writes the entry block into `<root>/AGENTS.md` (created when missing). An existing block is replaced between its
 * markers only; a file with no block gets it appended. A file whose markers are unpaired or out of order is refused
 * (an Error naming it), never repaired, so owner text is never rewritten. With no Clossys agent installed it writes nothing.
 */
export function ensureEntryBlock(root: string): EntryBlockResult {
  const file = join(root, "AGENTS.md");
  const scope = coveredScope(root);
  if (!scope.length) return { file, outcome: "none" };
  const block = entryBlock(scope);
  const current = existsSync(file) ? readFileSync(file, "utf8") : "";
  const start = current.indexOf(ENTRY_START);
  const end = current.indexOf(ENTRY_END);
  const twice = (marker: string, at: number) => at >= 0 && current.indexOf(marker, at + marker.length) >= 0;
  if ((start < 0) !== (end < 0) || (start >= 0 && end < start) || twice(ENTRY_START, start) || twice(ENTRY_END, end)) {
    throw new Error(`AGENTS.md: the clossys entry block markers (${ENTRY_START} ... ${ENTRY_END}) are unpaired; fix them by hand, then re-run clossys init`);
  }
  if (start >= 0) {
    const next = current.slice(0, start) + block + current.slice(end + ENTRY_END.length);
    if (next === current) return { file, outcome: "present" };
    writeFileSync(file, next);
    return { file, outcome: "updated" };
  }
  const separator = current === "" ? "" : current.endsWith("\n\n") ? "" : current.endsWith("\n") ? "\n" : "\n\n";
  writeFileSync(file, `${current}${separator}${block}\n`);
  return { file, outcome: "added" };
}
