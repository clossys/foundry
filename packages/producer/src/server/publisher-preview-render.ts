const execute = promisify(execFile);
const producerRequire = createRequire(import.meta.url);
const inside = (root: string, file: string): boolean => {
  const rel = relative(resolve(root), resolve(file)); return !isAbsolute(rel) && rel !== ".." && !rel.startsWith(`..${sep}`);
};
export async function confinedPreviewFile(root: string, file: string): Promise<string> {
  if (!file || isAbsolute(file) || /[\\\x00-\x1f%?#]/.test(file) || file.split("/").some(part => part === ".." || part === "." || !part)) throw new Error("Invalid publication source path");
  const target = resolve(root, file);
  if (!inside(root, target)) throw new Error("Publication source escapes preview");
  for (let current = target; ; current = dirname(current)) {
    if ((await lstat(current)).isSymbolicLink()) throw new Error("Publication aliases are not followed");
    if (dirname(current) === current) break;
  }
  if (!(await lstat(target)).isFile()) throw new Error("Publication source must be a regular file");
  return target;
}
export async function previewSource(root: string, file: string): Promise<Buffer> {
  const path = await confinedPreviewFile(root, file);
  const handle = await open(path, constants.O_RDONLY | constants.O_NOFOLLOW | constants.O_NONBLOCK);
  try {
    const opened = await handle.stat(), current = await lstat(await confinedPreviewFile(root, file));
    if (!opened.isFile() || opened.ino !== current.ino || opened.dev !== current.dev) throw new Error("Publication source changed during read");
    return await handle.readFile();
  } finally { await handle.close(); }
}
/** Native app-local files carry a comment envelope, including JSON descriptors. */
export function generatedBody(source: string): string {
  const match = /^\/\* generated by clossys publish; do not edit\nclossys-digest: sha256:([a-f0-9]{64})\n\*\/\n/.exec(source);
  if (!match) throw new Error("Published source lacks its generated digest");
  const body = source.slice(match[0].length);
  if (createHash("sha256").update(body).digest("hex") !== match[1]) throw new Error("Published source differs from its generated digest");
  return body;
}
const escape = (value: string) => value.replace(/[&<>"']/g, character => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[character]!);
export interface NativePreviewPage { root: string; entry: string; exportName?: string; title?: string; description?: string; ogImage?: string }

/** Designer's shipped stylesheets a served page may link, each at `/__designer/<file>`. */
export const DESIGNER_STYLESHEETS: ReadonlySet<string> = new Set(["compiled.css", "specimen-frame.css"]);
export const designerStylesheetHref = (file: string): string => `/__designer/${file}`;
/** The bytes of one `DESIGNER_STYLESHEETS` file from the installed Designer package; undefined for any other name. */
export async function designerStylesheet(file: string): Promise<Buffer | undefined> {
  return DESIGNER_STYLESHEETS.has(file) ? readFile(join(resolveAgent("designer").packageRoot, "styles", file)) : undefined;
}
/** A native preview's bundled CSS, served by content hash under the preview's assets route. */
export const BUNDLE_STYLES = "__bundle/";
const bundledStyles = new Map<string, string>();
function holdBundledStylesheet(css: string): string {
  const hash = createHash("sha256").update(css).digest("hex");
  bundledStyles.delete(hash); bundledStyles.set(hash, css);
  while (bundledStyles.size > 64) bundledStyles.delete(bundledStyles.keys().next().value!);
  return hash;
}
export function bundledPreviewStylesheet(file: string): string | undefined {
  const hash = /^([a-f0-9]{64})\.css$/.exec(file)?.[1];
  return hash === undefined ? undefined : bundledStyles.get(hash);
}

/** Render actual generated modules in a short-lived child with no parent run token. */
export async function renderNativePreview(page: NativePreviewPage): Promise<Buffer> {
  const entry = await confinedPreviewFile(page.root, page.entry);
  if (!/\.(?:tsx?|jsx?|mjs)$/.test(entry)) throw new Error("Unsupported native page module");
  const directory = await mkdtemp(join(tmpdir(), "producer-published-page-"));
  try {
    const outfile = join(directory, "publication.mjs");
    const result = await build({
      stdin: { contents: `import { renderToStaticMarkup } from "react-dom/server"; import * as page from ${JSON.stringify(entry)}; const render = page[${JSON.stringify(page.exportName ?? "default")}]; if(typeof render !== "function") throw new Error("Published page export is unavailable"); process.stdout.write(renderToStaticMarkup(await render()));`, resolveDir: page.root, sourcefile: "producer-preview-entry.tsx" },
      outfile, bundle: true, write: false, format: "esm", platform: "node", target: "node22", jsx: "automatic", logLevel: "silent",
      nodePaths: producerRequire.resolve.paths("react") ?? [],
      banner: { js: `import { createRequire as __previewRequire } from "node:module"; const require = __previewRequire(${JSON.stringify(import.meta.url)});` },
      plugins: [{ name: "confined-native-preview", setup(context) {
        // Preserve installed dependency module URLs: libraries can load their
        // own JSON/assets with createRequire(import.meta.url).
        context.onResolve({ filter: /^[^./]/ }, args => {
          const entry = import.meta.resolve(args.path);
          return { path: entry.startsWith("file:") ? fileURLToPath(entry) : entry, external: true };
        });
        context.onLoad({ filter: /\.(?:tsx?|jsx?|mjs|css|json)$/ }, async args => {
          if (!inside(page.root, args.path)) return undefined; // Installed third-party runtime dependencies use normal Node resolution.
          const rel = relative(page.root, args.path).split(sep).join("/");
          const source = await previewSource(page.root, rel);
          const ext = args.path.split(".").at(-1)!;
          return { contents: generatedBody(source.toString("utf8")), loader: ext === "mjs" ? "js" : ext as "tsx" | "ts" | "jsx" | "js" | "css" | "json", resolveDir: dirname(args.path) };
        });
        context.onResolve({ filter: /^\./ }, args => {
          if (args.importer && inside(page.root, args.importer) && !inside(page.root, resolve(args.resolveDir, args.path))) throw new Error("Native publication import escapes generated preview");
          return undefined;
        });
      } }],
    });
    const js = result.outputFiles?.find(file => file.path.endsWith(".mjs"));
    if (!js) throw new Error("Native publication did not produce a runnable page");
    await writeFile(outfile, js.contents);
    const { stdout } = await execute(process.execPath, [outfile], { cwd: directory, env: { NODE_ENV: "production" }, timeout: 20_000, maxBuffer: 8 * 1024 * 1024 });
    if (!stdout.trim()) throw new Error("Native publication rendered no page");
    // Stylesheets are linked, never inlined: the installed Designer runtime's shipped utility rules
    // (DESIGNER_STYLESHEETS), the exact emitted consumer theme (the preview's own assets route) and
    // the bundle's own CSS (held by content hash). Selection stays in generated modules.
    const links = [designerStylesheetHref("compiled.css")];
    // The emitted consumer theme is required: a publication without it is not rendered unstyled.
    try { await previewSource(page.root, "theme.css"); }
    catch (error) { throw new Error(`Native publication has no readable emitted theme.css: ${error instanceof Error ? error.message : String(error)}`); }
    links.push("../assets/theme.css");
    const bundled = (result.outputFiles ?? []).filter(file => file.path.endsWith(".css")).map(file => file.text).join("\n");
    if (bundled) links.push(`../assets/${BUNDLE_STYLES}${holdBundledStylesheet(bundled)}.css`);
    const head = links.map(href => `<link rel="stylesheet" href="${escape(href)}">`).join("");
    const metadata = `${page.title === undefined ? "" : `<title>${escape(page.title)}</title>`}${page.description === undefined ? "" : `<meta name="description" content="${escape(page.description)}">`}${page.ogImage === undefined ? "" : `<meta property="og:image" content="${escape(page.ogImage)}">`}`;
    return Buffer.from(`<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">${metadata}${head}</head><body>${stdout}</body></html>`);
  } finally { await rm(directory, { recursive: true, force: true }); }
}
