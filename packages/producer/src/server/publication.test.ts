function get(path: string, method = "GET", headers: Record<string, string> = {}) {
  return new Promise<{ status: number; text: string; headers: Record<string, any> }>((resolve, reject) => {
    const req = request({ hostname: "127.0.0.1", port: server!.port, path, method, headers }, response => {
      let text = ""; response.setEncoding("utf8"); response.on("data", value => { text += value; }); response.on("end", () => resolve({ status: response.statusCode!, text, headers: response.headers }));
    }); req.on("error", reject); req.end();
  });
}
async function publicationFixture(file = "site/home.html") {
  const base = previewRoot(root, "example");
  const manifest = { schemaVersion: 1, publication: "example", sourceApp: "apps/web", format: "web.page.responsive", routes: [{ id: "home", path: "/", locale: "en", source: { file, export: "default" } }], contentMap: { version: 1, publicationId: "example", entries: [{ id: "home", path: "/", title: "Published home", description: "Actual descriptor description", kind: "page", order: 0, source: { frameId: "frames.auth-shell", sectionIds: ["sections.empty-state"] } }] } };
  await put(join(base, "preview.json"), generated(JSON.stringify(manifest)));
  return { base, manifest };
}

it("serves only emitted preview HTML and known assets with the existing loopback guards and sandbox", async () => {
  const { base } = await publicationFixture();
  const html = '<!doctype html><title>Published home</title><h1>Published artifact</h1><script>parent.document.body.dataset.escaped="yes"</script>';
  await put(join(base, "site/home.html"), html);
  await put(join(base, "theme.css"), generated("body { color: rebeccapurple; }"));
  await put(join(base, "assets/mark.svg"), '<svg xmlns="http://www.w3.org/2000/svg"/>');
  await put(join(base, "source.tsx"), "export default function Page() {}\n");
  await launch();
  const metadata = JSON.parse((await get("/api/publication")).text);
  expect(metadata).toMatchObject({ state: "ready", publication: "example", pages: [{ id: "home", route: "/", title: "Published home", description: "Actual descriptor description", emitted: true, previewUrl: "/preview/example/pages/home.html" }] });
  expect(metadata.pages[0].indexing).toBeUndefined(); expect(metadata.pages[0].lastPublished).toBeUndefined();
  const page = await get(metadata.pages[0].previewUrl);
  expect(page.status).toBe(200); expect(page.text).toBe(html);
  expect(page.headers["content-type"]).toContain("text/html"); expect(page.headers["content-security-policy"]).toContain("sandbox;");
  expect(page.headers["content-security-policy"]).not.toContain("allow-scripts"); expect(page.headers["content-security-policy"]).not.toContain("allow-same-origin");
  expect((await get("/preview/example/assets/theme.css")).text).toBe("body { color: rebeccapurple; }");
  expect((await get("/preview/example/assets/assets/mark.svg")).headers["content-type"]).toBe("image/svg+xml");
  expect((await get(metadata.pages[0].previewUrl, "HEAD")).text).toBe("");
  expect((await get(metadata.pages[0].previewUrl, "GET", { Host: "example.test" })).status).toBe(403);
  expect((await get(metadata.pages[0].previewUrl, "GET", { Origin: "null" })).status).toBe(403);
  expect((await get(metadata.pages[0].previewUrl, "POST")).status).toBe(403);
  const token = JSON.parse((await get("/api/config")).text).token;
  expect((await get(metadata.pages[0].previewUrl, "POST", { Origin: server!.url, "X-Clossys-Token": token })).status).toBe(405);
  for (const path of ["/preview/example/assets/source.tsx", "/preview/example/assets/preview.json", "/preview/example/assets/.manifest.json"]) expect((await get(path)).status).toBe(415);
  for (const path of ["/preview/example/assets/%2e%2e/preview.json", "/preview/example/assets/%252e%252e/preview.json", "/preview/example/assets/%5cetc/passwd"]) expect((await get(path)).status).toBeOneOf([400, 403, 415]);
  await put(join(root, "outside.html"), "private outside file");
  await symlink(join(root, "outside.html"), join(base, "escape.html"));
  expect((await get("/preview/example/assets/escape.html")).status).toBe(403);
}, 45_000);

it("reports unpublished, invalid and missing source states without inventing a page", async () => {
  await launch(); expect(JSON.parse((await get("/api/publication")).text)).toEqual({ state: "missing", message: "Not published yet", command: "clossys publish --target preview" });
  const { base } = await publicationFixture();
  expect(JSON.parse((await get("/api/publication")).text).pages[0].emitted).toBe(false);
  expect((await get("/preview/example/pages/home.html")).status).toBe(404);
  await writeFile(join(base, "preview.json"), "manually changed descriptor");
  expect(JSON.parse((await get("/api/publication")).text).state).toBe("error");
  expect((await get("/preview/example/pages/home.html")).status).toBe(403);
});

it("renders a real Publisher-emitted async route with its actual Designer page body", async () => {
  const fixtures = await agentModule("publisher", "web/__fixtures__/content-route.js");
  const source = await agentModule("publisher", "web/content-route-source.js");
  const content = fixtures.contentRouteFixture();
  const input = fixtures.withApprovedRouteCopy({ ...content, registry: { ...content.registry, workspace: { ...content.registry.workspace, deployTargets: content.registry.workspace.deployTargets.map((target: any) => ({ ...target, origin: "https://example.test" })) } }, publishing: { brand: "Example", manifest: { defaultLocale: "en", locales: [{ tag: "en", dir: "ltr", state: "active" }], fallback: {} }, bodyServedLocales: { en: ["en"] }, existingUrls: ["https://example.test/sign-in"] } });
  const route = source.createContentRouteManifest({ registry: input.registry, locale: input.locale, loader: { file: "src/content-loader.ts", export: "loadContentRoute" } }).routes[0];
  const { base } = await publicationFixture(route.source.file);
  await put(join(base, route.source.file), generated(source.emitContentRoutePage(route)));
  await put(join(base, "src/content-loader.ts"), generated(`export async function loadContentRoute() { return ${JSON.stringify(input)}; }\n`));
  await put(join(base, "theme.css"), generated(":root { --preview-rendered: 1; }"));
  const rendered = (await renderNativePreview({ root: base, entry: route.source.file })).toString("utf8");
  expect(rendered).toContain('data-ds-leaf="frames.auth-shell"'); expect(rendered).toContain('data-ds-leaf="sections.empty-state"');
  expect(rendered).toContain("Sign in to continue"); expect(rendered).not.toContain("clossys-digest:");
  await launch(); const response = await get("/preview/example/pages/home.html");
  expect(response.status).toBe(200); expect(response.text).toContain("Sign in to continue");
  await put(join(base, "src/content-loader.ts"), (await readFile(join(base, "src/content-loader.ts"), "utf8")) + "// hand edit\n");
  expect((await get("/preview/example/pages/home.html")).status).toBe(403);
}, 45_000);
