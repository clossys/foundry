/** Unknown consumer values remain unbound; codes are never prettified into words. */
export function publisherValueRef(parent: string, id: string): PublisherCopyRef | undefined {
  const names = Object.hasOwn(PUBLISHER_VALUE_NAME_REFS, parent) ? PUBLISHER_VALUE_NAME_REFS[parent] : undefined;
  return names && Object.hasOwn(names, id) ? names[id] : undefined;
}

export type PublisherValueNames = (parent: string, id: string) => string | undefined;

/** Resolve through the host: no record import, approval or activation occurs here. */
export function createPublisherValueNames(resolver: PublisherCopyResolver, locale?: string): PublisherValueNames {
  return (parent, id) => {
    const ref = publisherValueRef(parent, id);
    return ref === undefined ? undefined : publisherCopy(resolver, { ...ref, ...(locale === undefined ? {} : { locale }) });
  };
}
