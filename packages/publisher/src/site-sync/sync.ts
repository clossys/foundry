import { lstat, mkdir, readFile, readdir, unlink, writeFile } from "node:fs/promises";
import { dirname, isAbsolute, join, relative, resolve, sep } from "node:path";
import { emitAppLocal, parseGeneratedText, verifyAppLocal, writeAppLocal } from "./emitter.js";
import { createSiteSyncPlan, siteSyncHash, siteSyncJson, siteSyncPath, type SiteSyncPlan } from "./plan.js";
import { generatedText } from "./emitter.js";
import type { SiteSyncFinding, SiteSyncOptions, SiteSyncResult } from "./contract.js";

const inventoryName = ".publisher-site-sync.json";
async function safe(path: string): Promise<void> {
  for (let current = resolve(path); ; current = dirname(current)) {
    try { if ((await lstat(current)).isSymbolicLink()) throw new TypeError("Site sync refuses symbolic links"); }
    catch (error) { if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error; }
    if (dirname(current) === current) break;
  }
}
function contained(root: string, path: string): string {
  siteSyncPath(path);
  const destination = resolve(root, path), part = relative(root, destination);
  if (isAbsolute(part) || part === ".." || part.startsWith(`..${sep}`)) throw new TypeError("Generated route leaves the selected application");
  return destination;
}
async function text(path: string): Promise<string | undefined> {
  await safe(path);
  try { if (!(await lstat(path)).isFile()) throw new TypeError("Generated route must be a regular file"); return await readFile(path, "utf8"); }
  catch (error) { if ((error as NodeJS.ErrnoException).code === "ENOENT") return; throw error; }
}
async function priorInventory(root: string): Promise<Record<string, string>> {
  const source = await text(join(root, inventoryName));
  if (source === undefined) return {};
  const value: unknown = JSON.parse(parseGeneratedText(source).body);
  if (!value || typeof value !== "object" || Array.isArray(value)) throw new TypeError("Invalid site sync inventory");
  for (const [path, hash] of Object.entries(value)) {
    siteSyncPath(path);
    if ((!path.startsWith("app/") && path !== "redirects.generated.mjs") || typeof hash !== "string" || !/^[a-f0-9]{64}$/.test(hash)) throw new TypeError("Invalid site sync inventory entry");
  }
  return value as Record<string, string>;
}
async function routeInventory(root: string, prefix = "app"): Promise<string[]> {
  await safe(join(root, prefix));
  let entries;
  try { entries = await readdir(join(root, prefix), { withFileTypes: true }); }
  catch (error) { if ((error as NodeJS.ErrnoException).code === "ENOENT") return []; throw error; }
  const result: string[] = [];
  for (const entry of entries) {
    const path = `${prefix}/${entry.name}`;
    if (entry.isDirectory()) result.push(...await routeInventory(root, path));
    else if (entry.isSymbolicLink()) throw new TypeError("Site sync refuses symbolic links");
    else if (/\/(?:page|route)\.[jt]sx?$/.test(path)) result.push(path);
  }
  return result;
}
/** Inspect everything before writing: authored routes and hand edits are never overwritten. */
export async function applySiteSyncPlan(plan: SiteSyncPlan, check = false): Promise<SiteSyncResult> {
  const root = resolve(plan.emission.appDir), outDir = resolve(plan.emission.outDir);
  if (outDir !== join(root, "src/clossys")) throw new TypeError("Site sync requires the canonical app-local output directory");
  await safe(root); await safe(outDir);
  const prior = await priorInventory(root), findings: SiteSyncFinding[] = [];
  const add = (kind: SiteSyncFinding["kind"], path: string, message: string) => findings.push({ kind, path, message });
  const files = { ...plan.files, [inventoryName]: generatedText(`${siteSyncJson(Object.fromEntries(Object.entries(plan.files).sort(([a], [b]) => a.localeCompare(b)).map(([path, source]) => [path, siteSyncHash(source)])))}\n`) };
  for (const [path, expected] of Object.entries(files)) {
    const actual = await text(contained(root, path));
    if (actual === undefined) { if (check) add("missing", path, "Expected generated site file is missing"); continue; }
    try { parseGeneratedText(actual); }
    catch { add("hand-edit", path, "Authored or hand-edited site file would be overwritten"); continue; }
    if (actual !== expected && check) add("stale", path, "Generated site file differs from the current publication");
  }
  const removed = Object.keys(prior).filter(path => !Object.hasOwn(plan.files, path));
  for (const path of removed) {
    const actual = await text(contained(root, path));
    if (actual === undefined) continue;
    try { parseGeneratedText(actual); }
    catch { add("hand-edit", path, "Hand-edited obsolete site file cannot be removed"); continue; }
    if (siteSyncHash(actual) !== prior[path]) add("hand-edit", path, "Obsolete site file differs from the recorded generated bytes");
    else if (check) add("extra", path, "Obsolete generated route remains in the site");
  }
  for (const path of await routeInventory(root)) if (!Object.hasOwn(plan.files, path) && !removed.includes(path)) add("extra", path, "Unmanaged route is absent from the selected publication");
  const appLocalFindings = await verifyAppLocal(outDir, plan.emission);
  for (const finding of appLocalFindings) if (check || ["hand-edit", "extra", "clossys-import"].includes(finding.kind) || finding.path === "package.json") {
    add(finding.kind, finding.path === "package.json" ? finding.path : `src/clossys/${finding.path}`, finding.message);
  }
  if (findings.length) return { exitCode: 1, findings, files: Object.keys(files).sort() };
  if (!check) {
    // All outputs, source envelopes and destinations have been validated above.
    for (const [path, source] of Object.entries(plan.emission.files)) { parseGeneratedText(source); await safe(contained(outDir, path)); }
    for (const path of Object.keys(files)) await safe(contained(root, path));
    await writeAppLocal(outDir, plan.emission);
    for (const path of removed) { const destination = contained(root, path); if (await text(destination) !== undefined) await unlink(destination); }
    for (const [path, source] of Object.entries(files)) { const destination = contained(root, path); await mkdir(dirname(destination), { recursive: true }); await writeFile(destination, source); }
  }
  return { exitCode: 0, findings: [], files: Object.keys(files).sort() };
}
export async function syncSite(options: SiteSyncOptions): Promise<SiteSyncResult> {
  const emission = await emitAppLocal({ root: options.root, target: options.target });
  return applySiteSyncPlan(createSiteSyncPlan(options, emission), options.check);
}
