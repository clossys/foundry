import { createHash } from "node:crypto";

export const appLocalHash = (body: string): string => createHash("sha256").update(body).digest("hex");
/** JSON outputs use the same comment envelope as TypeScript and CSS. Parse their body with parseAppLocalJson. */
export function generatedText(body: string): string {
  if (body.includes("@clossys/")) throw new Error("Generated source contains an unresolved first-party reference");
  return `/* generated by clossys publish; do not edit\nclossys-digest: sha256:${appLocalHash(body)}\n*/\n${body}`;
}
export function parseGeneratedText(source: string): { readonly digest: string; readonly body: string } {
  const header = /^\/\* generated by clossys publish; do not edit\nclossys-digest: sha256:([a-f0-9]{64})\n\*\/\n/.exec(source);
  if (!header) throw new Error("Generated header is missing or invalid");
  const body = source.slice(header[0].length), digest = header[1]!;
  if (appLocalHash(body) !== digest) throw new Error("Generated body differs from its digest");
  return { digest, body };
}
/** The single parser for header-enveloped dependencies.json and .manifest.json. */
export function parseAppLocalJson(source: string): unknown { return JSON.parse(parseGeneratedText(source).body); }
