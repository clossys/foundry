import { lstat, mkdir, open, readdir, readFile, writeFile } from "node:fs/promises";
import { constants } from "node:fs";
import { dirname, isAbsolute, join, relative, resolve, sep } from "node:path";
import { appLocalHash, parseAppLocalJson, parseGeneratedText } from "./format.js";
import type { AppLocalEmission } from "./emit.js";
import { firstPartyAppImports } from "./source.js";

export type AppLocalFindingKind = "missing" | "stale" | "hand-edit" | "extra" | "clossys-import";
export interface AppLocalFinding { readonly kind: AppLocalFindingKind; readonly path: string; readonly message: string }
export function safeAppLocalPath(path: string): string {
  if (!path || isAbsolute(path) || /^[a-z]:/i.test(path) || /[\\\u0000-\u001f]/.test(path) || path.split("/").some(part => !part || part === "." || part === "..")) throw new Error("Expected a contained relative output path");
  return path;
}
export function containedAppLocalPath(root: string, path: string): string {
  safeAppLocalPath(path);
  const target = resolve(root, path), rel = relative(resolve(root), target);
  if (isAbsolute(rel) || rel === ".." || rel.startsWith(`..${sep}`)) throw new Error("Output escapes destination");
  return target;
}
export async function noAppLocalSymlink(path: string): Promise<void> {
  for (let current = resolve(path); ; current = dirname(current)) {
    try { if ((await lstat(current)).isSymbolicLink()) throw new Error("Symbolic links are not supported"); }
    catch (cause) { if ((cause as NodeJS.ErrnoException).code !== "ENOENT") throw cause; }
    if (dirname(current) === current) break;
  }
}
async function regularText(path: string): Promise<string> {
  await noAppLocalSymlink(path);
  const file = await open(path, constants.O_RDONLY | constants.O_NOFOLLOW | constants.O_NONBLOCK);
  try { if (!(await file.stat()).isFile()) throw new Error("Expected a regular file"); return await file.readFile("utf8"); }
  finally { await file.close(); }
}
async function inventory(root: string, prefix = "", excluded: ReadonlySet<string> = new Set()): Promise<string[]> {
  const result: string[] = [];
  let entries;
  try { entries = await readdir(join(root, prefix), { withFileTypes: true }); }
  catch (cause) { if ((cause as NodeJS.ErrnoException).code === "ENOENT") return []; throw cause; }
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    const path = prefix ? `${prefix}/${entry.name}` : entry.name;
    safeAppLocalPath(path);
    if (entry.isDirectory()) { if (!excluded.has(entry.name)) result.push(...await inventory(root, path, excluded)); } else result.push(path);
  }
  return result;
}
/** Writes only expected generated files, after validating the complete plan and all destination ancestors. */
export async function writeAppLocal(directory: string, expected: AppLocalEmission): Promise<void> {
  const plan = Object.entries(expected.files);
  for (const [path, source] of plan) {
    const destination = containedAppLocalPath(directory, path);
    parseGeneratedText(source); if (source.includes("@clossys/")) throw new Error("Unresolved first-party output");
    await noAppLocalSymlink(destination);
  }
  for (const [path, source] of plan) {
    const destination = containedAppLocalPath(directory, path);
    await mkdir(dirname(destination), { recursive: true }); await writeFile(destination, source);
  }
}
/** Recompute expected output separately, then compare. Verification never creates, repairs, or removes a file. */
export async function verifyAppLocal(directory: string, expected: AppLocalEmission): Promise<AppLocalFinding[]> {
  await noAppLocalSymlink(directory);
  const findings: AppLocalFinding[] = [], present = await inventory(directory), bodies = new Map<string, string>();
  const add = (kind: AppLocalFindingKind, path: string, message: string) => findings.push({ kind, path, message });
  for (const path of Object.keys(expected.files)) {
    containedAppLocalPath(directory, path);
    let source: string;
    try { source = await regularText(join(directory, path)); }
    catch (cause) { if ((cause as NodeJS.ErrnoException).code === "ENOENT") add("missing", path, "Expected generated file is missing"); else add("hand-edit", path, "Generated path is not a regular source file"); continue; }
    bodies.set(path, source);
    if (source.includes("@clossys/")) add("clossys-import", path, "Generated file contains a first-party reference");
    try { parseGeneratedText(source); if (source !== expected.files[path]) add("stale", path, "Generated bytes differ from current cells"); }
    catch { add("hand-edit", path, "Generated header or body digest is invalid"); }
  }
  let manifest: Record<string, unknown> = {};
  const actualManifest = bodies.get(".manifest.json");
  if (actualManifest) try {
    const value = parseAppLocalJson(actualManifest);
    if (!value || typeof value !== "object" || Array.isArray(value)) throw new Error("Invalid manifest");
    manifest = value as Record<string, unknown>;
    for (const [path, digest] of Object.entries(manifest)) {
      safeAppLocalPath(path);
      if (path === ".manifest.json" || typeof digest !== "string" || !/^[a-f0-9]{64}$/.test(digest)) throw new Error("Invalid manifest entry");
      const source = bodies.get(path);
      if (source !== undefined && appLocalHash(source) !== digest && source === expected.files[path]) add("stale", ".manifest.json", "Manifest does not hash the emitted bytes");
    }
  } catch { add("hand-edit", ".manifest.json", "Generated manifest cannot be verified"); }
  for (const path of present) if (!Object.hasOwn(expected.files, path) || path !== ".manifest.json" && actualManifest && !Object.hasOwn(manifest, path)) {
    add("extra", path, "File is absent from the generated manifest");
    if (!Object.hasOwn(expected.files, path)) try { if ((await regularText(join(directory, path))).includes("@clossys/")) add("clossys-import", path, "Extra source contains a first-party reference"); } catch { /* The extra path remains a finding. */ }
  }
  if (expected.appDir) {
    const manifestPath = join(expected.appDir, "package.json");
    try {
      const manifestSource = await regularText(manifestPath), app = JSON.parse(manifestSource);
      const dependencies = { ...app.dependencies, ...app.devDependencies, ...app.peerDependencies, ...app.optionalDependencies } as Record<string, unknown>;
      if (Object.keys(dependencies).some(name => name.startsWith("@clossys/"))) add("clossys-import", "package.json", "Application depends on a first-party package");
      for (const name of Object.keys(expected.dependencies)) if (typeof dependencies[name] !== "string") add("missing", "package.json", `Application dependency is missing: ${name}`);
    } catch (cause) { if ((cause as NodeJS.ErrnoException).code === "ENOENT") add("missing", "package.json", "Application package manifest is missing"); else throw cause; }
    // Dependency installs, build products and repository/state inventories are not application-authored source.
    const excluded = new Set(["node_modules", ".next", "dist", "build", "out", "coverage", ".git", ".state"]);
    for (const path of await inventory(expected.appDir, "", excluded)) {
      const absolute = join(expected.appDir, path), generated = relative(resolve(directory), absolute);
      if (generated !== ".." && !generated.startsWith(`..${sep}`) && !isAbsolute(generated)) continue;
      try {
        const metadata = await lstat(absolute);
        if (metadata.isSymbolicLink()) { add("hand-edit", path, "Application source alias cannot be verified"); continue; }
        if (/\.[cm]?[jt]sx?$/.test(path) && firstPartyAppImports({ path, content: await regularText(absolute) }).length) add("clossys-import", path, "Application source imports a first-party package");
      } catch { add("hand-edit", path, "Application source cannot be verified as a regular file"); }
    }
  }
  return findings;
}
