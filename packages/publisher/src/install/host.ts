/**
 * The Publisher host for installed and emitted pages. Every page Publisher writes mounts its
 * frame inside `PublisherHost` (`@clossys/publisher/web/host`), fed by the consumer's own
 * component selection module and its Writer copy for Designer shell strings. Publisher never
 * supplies a default selection: a page without one is a `need-component-selection` finding.
 *
 * The host is a client module, so a server page can render it while the selection's live
 * component namespaces stay on the client side of the boundary.
 */
import { posix } from "node:path";
import type { InstallFinding } from "./index.js";

/**
 * The consumer module that exports its `ConsumerComponentSelection` (profile, selectionHash,
 * descriptors and live `modules`). A `module` with a code extension is a substrate-relative file;
 * anything else is a package specifier. `export` defaults to `componentSelection`.
 */
export interface PageHostSelection { readonly module: string; readonly export?: string }

/** The export the generated host module names; pages import it from the host file. */
export const PAGE_HOST_EXPORT = "PageHost";
const CODE = /\.(?:[cm]?[jt]sx?)$/;
const IDENTIFIER = /^[A-Za-z_$][\w$]*$/;

/** The blocking finding for a page emitted without the consumer's component selection. */
export function needComponentSelection(page: string): InstallFinding {
  return { code: "need-component-selection", detail: `NEED component selection: ${page} mounts inside the Publisher host, which requires the consumer's component selection module; Publisher supplies no default` };
}

/** A relative import specifier from one substrate file to another, without the code extension. */
export function relativeSpecifier(from: string, to: string): string {
  const path = posix.relative(posix.dirname(from), to).replace(CODE, "");
  return path.startsWith(".") ? path : `./${path}`;
}

/** Writer copy for Designer shell references (skip link, navigation, banner labels), by ref id. */
async function shellText(copy: Readonly<Record<string, string>>): Promise<Record<string, string>> {
  const { SHELL_COPY_REFS } = await import("@clossys/designer/frames");
  const ids = new Set<string>();
  const walk = (value: unknown): void => {
    if (!value || typeof value !== "object") return;
    if (typeof (value as { id?: unknown }).id === "string") { ids.add((value as { id: string }).id); return; }
    for (const item of Object.values(value)) walk(item);
  };
  walk(SHELL_COPY_REFS);
  return Object.fromEntries([...ids].sort().filter(id => Object.hasOwn(copy, id)).map(id => [id, copy[id]!]));
}

export interface PageHostModuleOptions {
  readonly selection: PageHostSelection;
  /** Writer copy by key; the entries for Designer shell references are embedded. */
  readonly copy: Readonly<Record<string, string>>;
  /** Substrate-relative path the host module is written to. */
  readonly file: string;
}

/** The client host module a page imports: `PublisherHost` with the consumer selection and Writer shell copy. */
export async function pageHostModule(options: PageHostModuleOptions): Promise<string> {
  const name = options.selection.export ?? "componentSelection";
  if (!IDENTIFIER.test(name) || !options.selection.module) throw new Error("page host: the component selection needs a module and an identifier export");
  const specifier = CODE.test(options.selection.module) ? relativeSpecifier(options.file, posix.normalize(options.selection.module)) : options.selection.module;
  return [
    '"use client";',
    "// Generated by Publisher. The consumer's component selection and Writer shell copy around every page; rerun the install rather than editing this file.",
    'import { createElement, type ReactNode } from "react";',
    'import { PublisherHost } from "@clossys/publisher/web/host";',
    `import { ${name} as selection } from ${JSON.stringify(specifier)};`,
    `const shellText: Record<string, string> = ${JSON.stringify(await shellText(options.copy), null, 2)};`,
    "function shellCopy(ref: { readonly id: string; readonly locale?: string }) {",
    "  return Object.hasOwn(shellText, ref.id) ? { ref, text: shellText[ref.id]! } : undefined;",
    "}",
    `export function ${PAGE_HOST_EXPORT}({ children }: { children?: ReactNode }): ReactNode {`,
    "  return createElement(PublisherHost, { components: selection, shellCopy, children });",
    "}",
    "",
  ].join("\n");
}
