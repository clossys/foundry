#!/usr/bin/env node
/**
 * Copies the shared brief and engagement-context contracts, and a
 * byte-identical copy of their one checker implementation, into this
 * package at build time (issue #1173's #1475 follow-up): so
 * @clossys/strategist reads `clossys/brief.json` against the same
 * `docs/contracts/engagement-brief.json` and `engagement-context.json`
 * that @clossys/advisor and @clossys/launcher validate against, with no
 * runtime dependency on either package.
 *
 * Mirrors `packages/launcher/scripts/pack-skills.mjs`'s own
 * generated-contract step -- see that file and `scripts/lib/plan-contracts.mjs`,
 * whose `renderContractSchemaCopy()` this reuses for a byte-identical
 * checker copy -- but packs only the two contracts this package actually
 * validates against, not `docs/contracts/advisor-plan.json`, which
 * Launcher also packs and Strategist never reads.
 *
 * `src/generated/` is gitignored, like every other packed build output in
 * this repository.
 */
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { renderContractSchemaCopy } from "../../../scripts/lib/plan-contracts.mjs";

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = join(packageRoot, "..", "..");

/** The contracts packed. `engagement-brief.json` refers to `engagement-context.json` by file name for its optional `context` property's `$ref`. */
const BRIEF_CONTRACT_FILES = ["engagement-brief.json", "engagement-context.json"];
export const BRIEF_CONTRACTS_MODULE_PATH = "src/generated/brief-contracts.generated.ts";
export const CONTRACT_SCHEMA_COPY_PATH = "src/generated/contract-schema.generated.ts";

/** The generated data module's source text: the two packed contracts, parsed and re-serialized -- the same rendering shape `scripts/lib/plan-contracts.mjs`'s `renderPlanContractsModule()` uses, scoped to only the files this package validates against. */
function renderBriefContractsModule() {
  const entries = BRIEF_CONTRACT_FILES.map((name) => {
    const contract = JSON.parse(readFileSync(join(repoRoot, "docs", "contracts", name), "utf8"));
    return `  ${JSON.stringify(name)}: ${JSON.stringify(contract, null, 2).replace(/\n/g, "\n  ")},`;
  });
  return `// AUTO-GENERATED by this package's build-time packer (issue #1173, #1475).
// Do not edit by hand -- edits are overwritten on the next \`npm run build\`.
// Source of truth: docs/contracts/engagement-brief.json and
// engagement-context.json in this package's source repository. Every
// package that validates a brief packs this same shape.

/** The shared brief contracts this package validates against, keyed by their file name in docs/contracts/. */
export const BRIEF_CONTRACTS: Readonly<Record<string, Readonly<Record<string, unknown>>>> = {
${entries.join("\n")}
};
`;
}

const generatedDir = join(packageRoot, "src", "generated");
if (existsSync(generatedDir)) rmSync(generatedDir, { recursive: true, force: true });
mkdirSync(generatedDir, { recursive: true });
writeFileSync(join(packageRoot, BRIEF_CONTRACTS_MODULE_PATH), renderBriefContractsModule());
writeFileSync(join(packageRoot, CONTRACT_SCHEMA_COPY_PATH), renderContractSchemaCopy(repoRoot));
console.log("pack-brief-contract: wrote the brief and engagement-context contracts and the contract checker copy into src/generated/");
