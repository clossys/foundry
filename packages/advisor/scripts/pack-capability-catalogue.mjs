#!/usr/bin/env node
/**
 * Freezes a generated snapshot of the capability catalogue and the curated
 * kit presets into src/generated/, so the published advisor package ships
 * plain data with no runtime file or network I/O (mirrors the launcher's
 * own skill-catalogue packer).
 *
 * The generation algorithm itself lives once, in this repository's shared
 * script library, because this repository's own offering-kits gate needs
 * the identical logic without a build step. This script can reach across
 * this repository because it is a private build tool -- it is never part
 * of `files` in package.json and never ships.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { readFileSync } from "node:fs";
import { buildCapabilityCatalogue, loadClientProblems } from "../../../scripts/lib/capability-catalogue.mjs";

const advisorRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = join(advisorRoot, "..", "..");
const outDir = join(advisorRoot, "src", "generated");
const outFile = join(outDir, "offering.generated.ts");

const catalogue = buildCapabilityCatalogue(repoRoot);
const presetsPath = join(repoRoot, "docs", "contracts", "kit-presets.json");
const presets = JSON.parse(readFileSync(presetsPath, "utf8"));
const clientProblems = loadClientProblems(repoRoot);

mkdirSync(outDir, { recursive: true });

const banner = `// AUTO-GENERATED by this package's build-time packer (issue #1176).
// Do not edit by hand -- edits are overwritten on the next \`npm run build\`.
// Source of truth: this repository's role-loop archetypes, each package's
// own \`foundry\` block, the committed non-runtime closed-loop order
// (nonRuntimeOrder fallback), the curated kit presets, and the client
// problem vocabulary.
`;

const body = `${banner}
import type { CapabilityCatalogue } from "../capability-catalogue.js";
import type { KitPreset } from "../kit-presets.js";
import type { ClientProblem } from "../client-problems.js";

export const CAPABILITY_CATALOGUE_DATA: CapabilityCatalogue = ${JSON.stringify(catalogue, null, 2)} as const;

export const KIT_PRESETS_DATA: readonly KitPreset[] = ${JSON.stringify(presets.presets, null, 2)} as const;

export const CLIENT_PROBLEMS_DATA: readonly ClientProblem[] = ${JSON.stringify(clientProblems, null, 2)} as const;
`;

writeFileSync(outFile, body);

console.log(
  `pack-capability-catalogue: wrote ${catalogue.roles.length} role(s), ${presets.presets.length} preset(s), and ${clientProblems.length} client problem(s) to src/generated/offering.generated.ts`,
);
