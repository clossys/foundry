#!/usr/bin/env node
/**
 * Freezes a generated snapshot of the capability catalogue and the curated
 * kit presets into src/generated/, so the published advisor package ships
 * plain data with no runtime file or network I/O (mirrors the launcher's
 * own skill-catalogue packer).
 *
 * The generation algorithm itself lives once, in this repository's shared
 * script library, because this repository's own offering-kits gate needs
 * the identical logic without a build step. This script can reach across
 * this repository because it is a private build tool -- it is never part
 * of `files` in package.json and never ships.
 *
 * `renderOfferingModule` is exported so a test can render a catalogue built
 * from changed manifests and typecheck it against this package's own types
 * without writing the generated file.
 *
 * It also writes src/generated/plan-contracts.generated.ts (issue #1475):
 * the shared plan, brief and repository-inventory contracts as plain data,
 * rendered by the same function @clossys/launcher's own packer uses, so both
 * packages validate against byte-identical contracts.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { buildCapabilityCatalogue, loadClientProblems } from "../../../scripts/lib/capability-catalogue.mjs";
import { PLAN_CONTRACTS_MODULE_PATH, renderPlanContractsModule } from "../../../scripts/lib/plan-contracts.mjs";

const advisorRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = join(advisorRoot, "..", "..");

export const GENERATED_MODULE_PATH = join(advisorRoot, "src", "generated", "offering.generated.ts");

const banner = `// AUTO-GENERATED by this package's build-time packer (issue #1176).
// Do not edit by hand -- edits are overwritten on the next \`npm run build\`.
// Source of truth: this repository's role-loop archetypes, each package's
// own \`foundry\` block, the committed non-runtime closed-loop order
// (nonRuntimeOrder fallback), the curated kit presets, and the client
// problem vocabulary.
`;

/** The generated TypeScript module's source text. */
export function renderOfferingModule({ catalogue, presets, clientProblems }) {
  return `${banner}
import type { CapabilityCatalogue } from "../capability-catalogue.js";
import type { KitPreset } from "../kit-presets.js";
import type { ClientProblem } from "../client-problems.js";

export const CAPABILITY_CATALOGUE_DATA: CapabilityCatalogue = ${JSON.stringify(catalogue, null, 2)} as const;

export const KIT_PRESETS_DATA: readonly KitPreset[] = ${JSON.stringify(presets, null, 2)} as const;

export const CLIENT_PROBLEMS_DATA: readonly ClientProblem[] = ${JSON.stringify(clientProblems, null, 2)} as const;
`;
}

function main() {
  const catalogue = buildCapabilityCatalogue(repoRoot);
  const presets = JSON.parse(readFileSync(join(repoRoot, "docs", "contracts", "kit-presets.json"), "utf8")).presets;
  const clientProblems = loadClientProblems(repoRoot);

  mkdirSync(dirname(GENERATED_MODULE_PATH), { recursive: true });
  writeFileSync(GENERATED_MODULE_PATH, renderOfferingModule({ catalogue, presets, clientProblems }));

  writeFileSync(join(advisorRoot, ...PLAN_CONTRACTS_MODULE_PATH.split("/")), renderPlanContractsModule(repoRoot));

  console.log(
    `pack-capability-catalogue: wrote ${catalogue.roles.length} role(s), ${presets.length} preset(s), and ${clientProblems.length} client problem(s) to src/generated/offering.generated.ts, and the plan and brief contracts to ${PLAN_CONTRACTS_MODULE_PATH}`,
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
