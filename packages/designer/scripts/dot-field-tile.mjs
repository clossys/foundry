import { readFileSync, writeFileSync } from "node:fs";
import { generateDotFieldPath } from "../dist/backdrop/dot-field-tile.js";

const source = new URL("../src/backdrop/dot-field-tile-data.ts", import.meta.url);
const golden = new URL("../src/backdrop/dot-field-path.golden.txt", import.meta.url);
const path = generateDotFieldPath();
const generated = `// Generated by scripts/dot-field-tile.mjs (repository-only tooling; it does not ship); do not hand-edit.\nexport const DOT_FIELD_PATH = ${JSON.stringify(path)};\n`;
if (process.argv.includes("--write")) {
  writeFileSync(source, generated);
  writeFileSync(golden, path + "\n");
} else {
  if (readFileSync(source, "utf8") !== generated || readFileSync(golden, "utf8") !== path + "\n") throw new Error("Dot-field tile has drifted; rebuild Designer and run scripts/dot-field-tile.mjs --write.");
}
console.log(`Dot-field tile: ${Buffer.byteLength(path)} path bytes; seed 7, 18 cells, pitch 32, radius 1.5.`);
