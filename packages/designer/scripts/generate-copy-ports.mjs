import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";

const BEGIN = "// BEGIN GENERATED WRITER COPY PORT TYPES";
const END = "// END GENERATED WRITER COPY PORT TYPES";
const source = new URL("../../writer/src/catalog/slots/passages.json", import.meta.url);
const target = new URL("../src/runtime/sections/copy-ports.ts", import.meta.url);

/** Writer owns these keys and kinds; no Designer key inventory is maintained. */
export function emitCopyPortTypes(passages) {
  if (!Array.isArray(passages)) throw new TypeError("Writer passage slots must be an array");
  const seen = new Set();
  const lines = [BEGIN, "/** Generated by scripts/generate-copy-ports.mjs from Writer passage contracts. */", "export interface WriterSectionCopyPorts {"];
  for (const slot of [...passages].sort((a, b) => a.contract.sectionId.localeCompare(b.contract.sectionId))) {
    const id = slot.contract.sectionId;
    if (seen.has(id)) throw new TypeError(`Duplicate Writer section ${id}`);
    seen.add(id);
    lines.push(`  readonly ${JSON.stringify(id)}: {`);
    const fields = new Set();
    for (const field of slot.contract.copy.fields) {
      if (fields.has(field.key)) throw new TypeError(`Duplicate Writer copy key ${id}/${field.key}`);
      fields.add(field.key);
      const value = field.kind === "plain" ? "string" : field.kind === "rich" ? "ReactNode" : field.kind === "icu" ? `WriterIcuMessage<${JSON.stringify(field.key)}>` : undefined;
      if (!value) throw new TypeError(`Unsupported Writer copy kind ${field.kind}`);
      lines.push(`    readonly ${JSON.stringify(field.key)}${field.required ? "" : "?"}: ${value};`);
    }
    lines.push("  };");
  }
  lines.push("}", END);
  return lines.join("\n");
}
export function replaceCopyPortTypes(text, output) {
  const start = text.indexOf(BEGIN), end = text.indexOf(END);
  if (start < 0 || end < start) throw new TypeError("Generated copy-port markers are required");
  return text.slice(0, start) + output + text.slice(end + END.length);
}
export function main(args = process.argv.slice(2)) {
  if (args.some(arg => arg !== "--check")) throw new TypeError("Usage: generate-copy-ports.mjs [--check]");
  const before = readFileSync(target, "utf8");
  const after = replaceCopyPortTypes(before, emitCopyPortTypes(JSON.parse(readFileSync(source, "utf8"))));
  if (args.includes("--check")) {
    if (before !== after) { process.stderr.write("Writer copy-port types are stale; run node packages/designer/scripts/generate-copy-ports.mjs\n"); return 1; }
  } else writeFileSync(target, after);
  return 0;
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main();
