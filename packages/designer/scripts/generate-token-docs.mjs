#!/usr/bin/env node
// Generate the token reference from the same pure data consumers import.
// Reading source rather than dist keeps this check independent of build order.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const repository = new URL("../../../", import.meta.url);
const packageRoot = new URL("packages/designer/", repository);
export const tokenDocsPath = new URL("TOKENS.md", packageRoot);
export const tokenSkillPath = new URL("skill/SKILL.md", packageRoot);
const skillStart = "<!-- token-selection:start -->";
const skillEnd = "<!-- token-selection:end -->";

async function sourceData(relativePath) {
  const source = readFileSync(new URL(relativePath, packageRoot), "utf8");
  const { outputText, diagnostics } = ts.transpileModule(source, {
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext },
    reportDiagnostics: true,
  });
  if (diagnostics?.some(diagnostic => diagnostic.category === ts.DiagnosticCategory.Error)) {
    throw new Error(`Cannot transpile token data: ${relativePath}`);
  }
  return import(`data:text/javascript;base64,${Buffer.from(outputText).toString("base64")}`);
}

const code = value => `\`${String(value).replaceAll("`", "&#96;")}\``;

export async function generateTokenSkillSection() {
  const { TOKENS, TOKEN_FAMILIES } = await sourceData("src/tokens/tokens.ts");
  const { TOKEN_DISPLAY_GROUPS } = await sourceData("src/tokens/guidance.ts");
  const { name } = JSON.parse(readFileSync(new URL("package.json", packageRoot), "utf8"));
  const families = TOKEN_DISPLAY_GROUPS.reduce((count, group) => count + group.families.length, 0);
  return [
    skillStart,
    "Choose a token by its semantic purpose and actual CSS application, using the",
    `shared \`TOKEN_GUIDANCE\` from ${code(`${name}/tokens`)} and the generated`,
    "`TOKENS.md` reference. Read purpose, appropriate use, misuse and context before",
    "comparing values. `TOKEN_DISPLAY_GROUPS` supplies Group > Family navigation",
    `only: ${TOKEN_DISPLAY_GROUPS.length} groups and ${families} display families. It does not configure tokens or imply their type.`,
    `All ${Object.keys(TOKENS).length} properties, including aliases and composites, are independently referenceable`,
    "leaves with stable identity across brand and supported theme overlays and zero",
    "per-token configuration. Name the inspector \"Token details\"; configurable",
    `components begin at Components. Preserve the ${TOKEN_FAMILIES.length} legacy source families, references and`,
    "bookmarks. Do not duplicate guidance in a consumer or treat equal values",
    "and aliases as interchangeable roles. Read all five TokenDefinition fields",
    "(`property`, `family`, `value`, `brandable`, `themeDependent`) from `TOKENS`.",
    "Regenerate the reference and this section with `node scripts/generate-token-docs.mjs`",
    "(repository tooling, not shipped in the installed package)",
    "and check their freshness with `node scripts/check-token-docs.mjs`",
    "(repository tooling, not shipped in the installed package).",
    skillEnd,
  ].join("\n");
}

export function replaceTokenSkillSection(skill, replacement) {
  if (skill.split(skillStart).length !== 2 || skill.split(skillEnd).length !== 2) {
    throw new Error("The token-selection skill section must have exactly one marker pair.");
  }
  const start = skill.indexOf(skillStart);
  const end = skill.indexOf(skillEnd) + skillEnd.length;
  if (end <= start) throw new Error("The token-selection skill markers must be ordered.");
  return skill.slice(0, start) + replacement + skill.slice(end);
}

/** Deterministic, with no timestamp, locale-sensitive sorting or installed dist. */
export async function generateTokenDocs() {
  const [{ TOKENS, TOKEN_FAMILIES }, { TOKEN_GUIDANCE, TOKEN_DISPLAY_GROUPS }] = await Promise.all([
    sourceData("src/tokens/tokens.ts"),
    sourceData("src/tokens/guidance.ts"),
  ]);
  const { name } = JSON.parse(readFileSync(new URL("package.json", packageRoot), "utf8"));
  const properties = Object.keys(TOKENS).sort();
  const definitionFields = Object.keys(TOKENS[properties[0]]);
  const leaves = TOKEN_DISPLAY_GROUPS.flatMap(group => group.families.flatMap(family => family.properties));
  const sameProperties = values => JSON.stringify([...values].sort()) === JSON.stringify(properties);
  if (!sameProperties(Object.keys(TOKEN_GUIDANCE)) || !sameProperties(leaves) || new Set(leaves).size !== leaves.length) {
    throw new Error("Token guidance and display placement must each cover TOKENS exactly once.");
  }
  const familyCount = TOKEN_DISPLAY_GROUPS.reduce((count, group) => count + group.families.length, 0);
  const lines = [
    `# ${name}/tokens`,
    "",
    "<!-- Generated by scripts/generate-token-docs.mjs (repository tooling, not shipped). Edit shared token data, then regenerate. -->",
    "",
    `The flat registry contains ${properties.length} stable CSS properties. This reference groups them into ${TOKEN_DISPLAY_GROUPS.length} display groups and ${familyCount} display families for navigation. The ${TOKEN_FAMILIES.length} source families remain compatibility and provenance data; a display group does not imply a value type or a usage.`,
    "",
    "Each property has zero per-token configuration. Brand and supported theme overlays resolve the same property identity. The inspector is named **Token details**; configurable components start at Components. Existing legacy `oldGroup.sourceFamily@token` references and bookmarks keep their original identity. Display regrouping does not rename those references.",
    "",
    "Purpose, appropriate use, misuse, application context and specimen kind come from shared `TOKEN_GUIDANCE`. The explicit navigation tree is `TOKEN_DISPLAY_GROUPS`. Consumers import these records rather than maintain their own guidance. Default, source family, brandability and theme dependence below come directly from `TOKENS`; equal values and aliases do not make semantic roles interchangeable.",
    "",
    `TokenDefinition retains ${definitionFields.length} fields: ${definitionFields.map(code).join(", ")}. The property remains the stable identity while its supported brand and theme bindings resolve.`,
    "",
    "## Install and bind",
    "",
    "```bash",
    `npm install ${name}`,
    "```",
    "",
    "```css",
    `@import "${name}/tokens.css";`,
    '@import "./brand.css";',
    "```",
    "",
    `Start a brand overlay from ${code(`${name}/brand-template.css`)} and bind only slots that TOKENS marks brandable. Set ${code("data-brand-bound")} on the document root after supplying the real overlay. Non-brandable structural tokens retain their shipped contract. Use the brand-coverage and contrast gates documented in [README.md](README.md); a filled slot does not itself prove readable contrast.`,
    "",
    "Theme-dependent properties have light and dark declarations. Invariant aliases can still change appearance through their referenced property. A runtime CSS custom-property override cannot change a media query already compiled by Tailwind: breakpoint values are build-time thresholds, and native media conditions do not accept var().",
    "",
    "## Read Token details",
    "",
    "```ts",
    `import { TOKENS, TOKEN_GUIDANCE, TOKEN_DISPLAY_GROUPS } from "${name}/tokens";`,
    "",
    'const property = "--color-surface-raised";',
    "const definition = TOKENS[property];",
    "const guidance = TOKEN_GUIDANCE[property];",
    "console.log(definition?.value, guidance?.purpose, TOKEN_DISPLAY_GROUPS.length);",
    "```",
    "",
    "Application type describes the consuming CSS syntax, not a new field on TokenDefinition. A binding below is an application example, not proof that every component consumes that property. The actual resolved value depends on the supported brand and theme cascade. Check the named context before selecting an equal-valued alternative.",
    "",
    "## Display taxonomy",
    "",
    "| Group | Families | Properties |",
    "| --- | ---: | ---: |",
    ...TOKEN_DISPLAY_GROUPS.map(group => `| ${group.label} | ${group.families.length} | ${group.families.reduce((count, family) => count + family.properties.length, 0)} |`),
    "",
    "## Token reference",
  ];
  for (const group of TOKEN_DISPLAY_GROUPS) {
    lines.push("", `### ${group.label}`);
    for (const family of group.families) {
      lines.push("", `#### ${family.label} (${family.properties.length})`);
      for (const property of family.properties) {
        const definition = TOKENS[property];
        const guidance = TOKEN_GUIDANCE[property];
        const application = guidance.application;
        const variable = `var(${definition.property})`;
        const binding = application.cssProperty === "@media (min-width)"
          ? `@media (min-width: ${definition.value})`
          : `${application.cssProperty}: ${application.cssProperty === "transform" ? `scaleX(${variable})` : application.cssProperty === "backdrop-filter" ? `blur(${variable})` : variable}`;
        lines.push(
          "", `##### ${code(property)}`, "",
          `- Purpose: ${guidance.purpose}`,
          `- Appropriate use: ${guidance.use}`,
          `- Misuse or alternative: ${guidance.misuse}`,
          `- CSS binding: ${code(binding)}. Application type: ${code(application.valueType)}.`,
          `- Context: ${application.context}`,
          `- Specimen kind: ${code(guidance.specimen)}.`,
          `- Default: ${code(definition.value)}. Source family: ${code(definition.family)}. Brandable: ${definition.brandable ? "yes" : "no"}. Theme-dependent declaration: ${definition.themeDependent ? "yes" : "no"}.`,
        );
      }
    }
  }
  lines.push(
    "", "## Choosing and deriving a value", "",
    "Choose a semantic role before comparing numeric or color values. A chart-axis alias remains chart chrome; a density-row alias remains a sizing role; a decorative inverse ring does not become a keyboard focus indicator. Color status also needs a label or symbol, and a transparent wash must be checked on its composited ground.",
    "",
    "Compose a one-off intermediate spacing or timing value from existing roles with calc() when the supported layout needs it. Keep a genuinely new consumer-specific decision in that consumer's own extension namespace. Do not fork this registry or add per-token inspector configuration. A newly admitted shared token must also declare one explicit display placement and its own guidance.",
    "",
    "## Public data contract", "",
    "`TOKENS`, `TOKEN_FAMILIES`, `TOKEN_GUIDANCE` and `TOKEN_DISPLAY_GROUPS` are browser-safe data. `TokenDefinition` and `TokenFamily` retain their existing shape and identity. `TokenGuidance`, `TokenApplication`, `TokenValueType`, `TokenSpecimen`, `TokenDisplayFamily` and `TokenDisplayGroup` describe the additive metadata. No React runtime or new package subpath is required.",
    "",
    `File reading and installed-peer checks remain on ${code(`${name}/tokens/server`)}. See [README.md](README.md) for brand coverage, WCAG contrast, loading checks, supported CSS entry points and the complete API.`,
    "", "## Regenerate", "",
    "```bash", "node scripts/generate-token-docs.mjs # repository tooling, not shipped", "node scripts/check-token-docs.mjs # repository tooling, not shipped", "```",
    "", "Run these repository commands after editing the source registry, guidance or navigation. The checker compares the whole document byte for byte; no installed dist, timestamps or network requests participate.",
    "", "## Licence", "", "MIT", "",
  );
  return lines.join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  writeFileSync(tokenDocsPath, await generateTokenDocs());
  writeFileSync(tokenSkillPath, replaceTokenSkillSection(readFileSync(tokenSkillPath, "utf8"), await generateTokenSkillSection()));
  console.log("Token reference and selection skill generated.");
}
