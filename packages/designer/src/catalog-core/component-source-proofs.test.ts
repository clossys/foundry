// @vitest-environment node
import { describe, expect, it } from "vitest";
import table from "./component-source-proofs.json" with { type: "json" };
import { componentSourceKind, componentSourceProof, componentSourceProofKey } from "./component-source-proofs.js";
import * as reader from "../../scripts/lib/component-source-ast.mjs";
import { loadCatalogBundles } from "../catalog-bundles.js";

const { analyzeComponentSource, componentSourceProofs } = reader;

const stockFiles = loadCatalogBundles().sourceBundles.flatMap(bundle => bundle.files);

describe("component source proofs (generated by scripts/generate-component-source-proofs.mjs)", () => {
  it("is exactly the TypeScript AST reading of every current stock source, with no stale or extra proof", () => {
    expect(table).toEqual(componentSourceProofs(stockFiles));
    expect(Object.keys(table.proofs).length).toBeGreaterThan(0);
  });
  it("authenticates exact bytes and script kind only", () => {
    const file = stockFiles.find(file => file.path === "components/command/command.tsx")!;
    expect(componentSourceProof(file.path, file.content)).toEqual(table.proofs[componentSourceProofKey("tsx", file.content) as keyof typeof table.proofs]);
    expect(componentSourceProof(file.path, `${file.content} `)).toBeUndefined();
    expect(componentSourceProof("components/command/command.ts", file.content)).toBeUndefined();
    expect(componentSourceProof("components/command/command.css", file.content)).toBeUndefined();
  });
  it("keys every stock source exactly as the runtime does (the generator never loads dist digest code)", () => {
    for (const file of stockFiles) {
      expect(reader.componentSourceKind(file.path), file.path).toBe(componentSourceKind(file.path));
      const kind = componentSourceKind(file.path);
      if (kind) expect(reader.componentSourceProofKey(kind, file.content), file.path).toBe(componentSourceProofKey(kind, file.content));
    }
  });
});

describe("TypeScript AST source reading", () => {
  const read = (content: string, path = "source.tsx") => analyzeComponentSource(path, content);
  it("erases indexed, generic and heritage type grammar and keeps runtime and typeof reads", () => {
    const proof = read([
      'import * as React from "react"',
      'import type * as T from "react"',
      'type Dir = React.HTMLAttributes<HTMLDivElement>["dir"]',
      "interface Props extends React.ComponentPropsWithRef<\"div\"> { dir?: Dir }",
      "type Query = typeof T.Fragment",
      "class Legacy extends React.Component {}",
      "function Part<C extends React.ElementType>({ dir }: Omit<React.ComponentPropsWithRef<C>, \"children\"> & Props) {",
      "  const [open] = React.useState(false)",
      "  return <React.Fragment>{open ? dir : null}</React.Fragment>",
      "}",
      "export { Part }",
    ].join("\n"));
    expect(proof.functions).toEqual(["Part"]);
    expect(proof.exports).toEqual(["Part"]);
    expect(proof.namespaces).toEqual({ React: { module: "react", erased: false }, T: { module: "react", erased: true } });
    expect(proof.reads).toEqual([
      { module: "react", member: "Component", erased: false, typeQuery: false },
      { module: "react", member: "Fragment", erased: false, typeQuery: false },
      { module: "react", member: "Fragment", erased: true, typeQuery: true },
      { module: "react", member: "useState", erased: false, typeQuery: false },
    ]);
  });
  it("records a runtime read through a type-only namespace so the closure refuses it", () => {
    expect(read('import type * as R from "react"\nexport function Part() { return R.useState() }').reads).toEqual([{ module: "react", member: "useState", erased: true, typeQuery: false }]);
  });
  it.each([
    ["a syntax error", 'import * as React from "react"\nexport function Part() { return React.useState( }', /does not parse/],
    ["a shadowing parameter", 'import * as React from "react"\nexport function Part(React) { return React.useState() }', /shadowed/],
    ["a shadowing local", 'import * as React from "react"\nexport function Part() { const React = {}; return React }', /shadowed/],
    ["a computed read", 'import * as React from "react"\nexport function Part() { return React["useState"]() }', /computed/],
    ["an optional read", 'import * as React from "react"\nexport function Part() { return React?.useState() }', /escape or access/],
    ["a bare namespace value", 'import * as React from "react"\nexport function Part() { return take(React) }', /escape or access/],
    ["a destructured namespace", 'import * as React from "react"\nexport function Part() { const { useState } = React; return useState() }', /escape or access/],
    ["a shorthand namespace escape", 'import * as React from "react"\nexport function Part() { return { React } }', /escape or access/],
    ["an import-equals alias", 'import * as React from "react"\nimport Alias = React.Component\nexport function Part() { return null }', /escape or access/],
    ["a duplicate namespace", 'import * as React from "react"\nimport * as React from "other"\nexport function Part() { return null }', /duplicate|shadowed/],
  ])("refuses %s rather than guessing", (_label, content, error) => {
    expect(() => read(content)).toThrow(error);
  });
  it("proves nothing about aliases, re-exports, defaults or ambient declarations", () => {
    const proof = read('function A() { return null }\nexport default function B() { return null }\nexport declare function C(): null\nexport { A as D }\nexport { E } from "other"');
    expect(proof.functions).toEqual(["A", "B"]);
    expect(proof.exports).toEqual([]);
  });
});
