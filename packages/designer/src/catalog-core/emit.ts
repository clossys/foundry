import { tokenActivation } from "./token-css-syntax.js";
import { TOKENS } from "../tokens/tokens.js";
import { compare, unsafeText } from "./model.js";
import { stableStringify } from "./stable.js";
import { CatalogError, type EmitFile, type EmitOptions, type EmitTarget } from "./api.js";
import type { Resolved, ResolvedMember } from "./types.js";

const brandSelectors = { light: ":root[data-brand-bound]", mediaDark: '@media (prefers-color-scheme: dark) { :root[data-brand-bound]:not([data-theme="light"])', dark: ':root[data-brand-bound][data-theme="dark"]' };
const scaleSelectors = { light: ":root", mediaDark: '@media (prefers-color-scheme: dark) { :root:not([data-theme="light"])', dark: ':root[data-theme="dark"]' };
const namespaces: Readonly<Record<string, string>> = { "color-ramp": "color", "font-size": "text", "font-weight": "font-weight", "letter-spacing": "tracking", "line-height": "leading", typeface: "font", spacing: "spacing", breakpoint: "breakpoint", radius: "radius", shadow: "shadow", blur: "blur", easing: "ease", "container-width": "container", animation: "animate" };
/** Actual named outputs of the selected consumer, shared with component reads.
 * Explicit bindings name shipped CSS; open scale members name @theme outputs.
 * Different consumer members must never claim the same output property.
 */
export function emittedTokenProperties(resolved: Resolved): ReadonlyMap<string, { property: string; theme?: string }> {
  const shipped = new Set(Object.values(TOKENS).map(token => token.property));
  const owners = new Map<string, string>();
  const result = new Map<string, { property: string; theme?: string }>();
  for (const [id, member] of Object.entries(resolved.members)) {
    if (!id.startsWith("tokens.")) continue;
    const [, leaf, ...relative] = id.split(".");
    const namespace = namespaces[leaf ?? ""];
    const theme = namespace ? `--${namespace}-${relative.join("-")}` : undefined;
    if (member.emit && !shipped.has(member.emit)) throw new CatalogError(`emit: binding ${member.emit} is not a shipped token`);
    const property = member.emit ?? theme;
    if (!property) continue;
    for (const output of new Set([property, ...(theme ? [theme] : [])])) {
      if (!/^--[a-zA-Z0-9-]+$/.test(output)) throw new CatalogError("emit: invalid property");
      const owner = owners.get(output);
      if (owner !== undefined && owner !== id) throw new CatalogError(`emit: output property collision ${output} between ${owner} and ${id}`);
      owners.set(output, id);
    }
    result.set(id, { property, ...(theme ? { theme } : {}) });
  }
  return result;
}
export interface EmittedTokenDefinition {
  readonly id: string;
  readonly property: string;
  readonly target: "css-brand" | "css-scales" | "tailwind-theme";
  readonly theme: "light" | "dark";
  readonly value: string;
  readonly selector: string | null;
  readonly atRules: readonly { readonly name: string; readonly prelude: string }[];
}
export interface EmittedTokenManifest {
  readonly version: 1;
  readonly consumer: string;
  readonly selectionHash: string;
  readonly tokens: readonly { readonly id: string; readonly outputs: readonly string[]; readonly values: { readonly light: string; readonly dark: string } }[];
  readonly definitions: readonly EmittedTokenDefinition[];
}
type TokenRow = Pick<EmittedTokenDefinition, "id" | "property" | "target" | "theme" | "value">;
/** One materialization supplies CSS bytes and the expected declaration manifest. */
function materialize(resolved: Resolved, targets: readonly EmitTarget[], options: EmitOptions = {}): { files: EmitFile[]; definitions: EmittedTokenDefinition[] } {
  const files: EmitFile[] = [];
  const definitions: EmittedTokenDefinition[] = [];
  const properties = emittedTokenProperties(resolved);
  const byCss = new Map<string, ResolvedMember>(Object.values(resolved.members).filter(member => member.emit).map(member => [member.emit!, member]));
  const header = (target: EmitTarget): string => options.header === false ? "" : `/* Generated by @clossys/designer/catalog (${target}). Do not edit. consumer ${resolved.consumer} selection ${resolved.selectionHash} */\n`;
  if (!/^[a-z][a-z0-9-]*(?:@[a-z][a-z0-9-]*)?$/.test(resolved.consumer) || !/^fnv1a64:[a-f0-9]{16}$/.test(resolved.selectionHash)) throw new CatalogError("emit: invalid profile identity");
  const declaration = (property: string, value: string): string => {
    if (!/^--[a-zA-Z0-9-]+$/.test(property)) throw new CatalogError("emit: invalid property");
    const unsafe = unsafeText(value); if (unsafe) throw new CatalogError(`emit: unsafe CSS text (${unsafe})`);
    return `  ${property}: ${value};`;
  };
  const block = (selector: string, rows: readonly TokenRow[]): string => {
    if (rows.length === 0) return "";
    const opens = (selector.match(/\{/g) ?? []).length;
    const activation = tokenActivation(selector);
    definitions.push(...rows.map(row => ({ ...row, ...activation })));
    // mediaDark includes its media opening brace; the selector opening is ours.
    return `${selector} {\n${rows.map(row => declaration(row.property, row.value)).join("\n")}\n}${"\n}".repeat(opens)}\n`;
  };

  for (const target of [...new Set(targets)]) {
    if (target === "css-brand" || target === "css-scales") {
      const chosen = Object.values(TOKENS).filter(token => {
        const member = byCss.get(token.property); if (!member) return false;
        if (options.full && target === "css-brand") return true;
        if (target === "css-brand") return token.brandable;
        const original = resolved.baseline?.[token.property];
        return !token.brandable && (!original || ["light", "dark"].some(mode => (member.css[mode as "light" | "dark"] ?? member.css.light) !== (original[mode as "light" | "dark"] ?? original.light)));
      });
      const owners = new Map([...properties].map(([id, output]) => [output.property, id]));
      const row = (property: string, value: string, theme: "light" | "dark"): TokenRow => ({ id: owners.get(property)!, property, value, theme, target });
      const light = chosen.map(token => row(token.property, byCss.get(token.property)!.css.light, "light"));
      const dark = chosen.filter(token => options.full || token.themeDependent || (byCss.get(token.property)!.css.dark ?? byCss.get(token.property)!.css.light) !== byCss.get(token.property)!.css.light).map(token => { const member = byCss.get(token.property)!; return row(token.property, member.css.dark ?? member.css.light, "dark"); });
      if (options.extraVars) Object.keys(resolved.members).sort(compare).forEach((id, index) => {
        const member = resolved.members[id]!; if (member.emit || !id.startsWith("tokens.")) return;
        light.push({ id, property: `--studio-m-${index}`, value: member.css.light, theme: "light", target });
        dark.push({ id, property: `--studio-m-${index}`, value: member.css.dark ?? member.css.light, theme: "dark", target });
      });
      const selectors = options.selectors ?? (target === "css-brand" ? brandSelectors : scaleSelectors);
      files.push({ path: target === "css-brand" ? "brand.css" : "scales.css", contents: header(target) + [block(selectors.light, light), block(selectors.mediaDark, dark), block(selectors.dark, dark)].filter(Boolean).join("\n") });
    } else if (target === "css-fonts") {
      const imports = new Set<string>();
      for (const member of Object.values(resolved.members)) if (member.font?.kind === "fontsource") {
        const font = member.font;
        if (!/^@fontsource\/[a-z0-9-]+$/.test(font.package) || font.weights.some(weight => !Number.isInteger(weight) || weight < 1 || weight > 1000) || font.styles.some(style => style !== "normal" && style !== "italic")) throw new CatalogError("emit: malformed font payload");
        for (const weight of font.weights) for (const style of font.styles) imports.add(`@import "${font.package}/${weight}${style === "italic" ? "-italic" : ""}.css";`);
      }
      files.push({ path: "fonts.css", contents: header(target) + ([...imports].sort(compare).join("\n")) + (imports.size ? "\n" : "") });
    } else if (target === "notices") {
      const origins = Object.entries(resolved.members).filter(([,member]) => member.origin?.kind === "adopted").map(([member,value]) => ({ consumerMember: member, ...value.origin as Extract<import("./types.js").Origin,{kind:"adopted"}> })).sort((a,b) => compare(a.consumerMember,b.consumerMember));
      files.push({ path: "notices.json", contents: stableStringify({ version: 1, consumer: resolved.consumer, origins }) });
    } else if (target === "tailwind-theme") {
      const rows: [string, string][] = [];
      for (const [id, output] of properties) {
        if (output.theme) {
          const value = resolved.members[id]!.css.light;
          rows.push([output.theme, value]);
          definitions.push({ id, property: output.theme, value, target, theme: "light", selector: null, atRules: [{ name: "theme", prelude: "" }] });
        }
      }
      files.push({ path: "theme.css", contents: header(target) + `@theme {\n${rows.sort(([a], [b]) => compare(a, b)).map(([property, value]) => declaration(property, value)).join("\n")}\n}\n` });
    }
  }
  return { files, definitions };
}
export function emit(resolved: Resolved, targets: readonly EmitTarget[], options: EmitOptions = {}): EmitFile[] {
  return materialize(resolved, targets, options).files;
}
/** Expected selected source values, never observed computed styles or qualification. */
export function emittedTokenManifest(resolved: Resolved, targets: readonly EmitTarget[], options: EmitOptions = {}): EmittedTokenManifest {
  const { definitions } = materialize(resolved, targets, options);
  const tokens = [...emittedTokenProperties(resolved)].map(([id, output]) => ({ id,
    outputs: [...new Set([output.property, ...(output.theme ? [output.theme] : [])])],
    values: { light: resolved.members[id]!.css.light, dark: resolved.members[id]!.css.dark ?? resolved.members[id]!.css.light },
  }));
  return { version: 1, consumer: resolved.consumer, selectionHash: resolved.selectionHash, tokens, definitions };
}
