/**
 * Property-keyed semantic guidance. Display navigation does not configure
 * tokens or change their source identity. Defaults, aliases, brandability,
 * theme dependence and source families remain authoritative in TOKENS.
 * Application metadata describes a CSS use, not an inferred type of a group.
 */
export type TokenValueType = "color" | "length" | "number" | "font-family" | "font-style" | "font-weight" | "font-stretch" | "shadow" | "duration" | "easing";
export type TokenSpecimen = "surface" | "text" | "border" | "control" | "status" | "chart" | "font" | "space" | "size" | "icon" | "brandmark" | "radius" | "opacity" | "blur" | "shadow" | "ring" | "motion" | "layer" | "breakpoint";
export interface TokenApplication {
  /** Consuming CSS property, or a build-time media-query condition. */
  readonly cssProperty: string;
  /** The value's application syntax; never inferred from its display group. */
  readonly valueType: TokenValueType;
  readonly context: string;
}
export interface TokenGuidance {
  readonly purpose: string;
  readonly use: string;
  readonly misuse: string;
  readonly application: TokenApplication;
  /** Contextual example kind for a consumer to render, never component configuration. */
  readonly specimen: TokenSpecimen;
}
export interface TokenDisplayFamily {
  readonly id: string;
  readonly label: string;
  readonly properties: readonly string[];
}
export interface TokenDisplayGroup {
  readonly id: string;
  readonly label: string;
  readonly families: readonly TokenDisplayFamily[];
}

