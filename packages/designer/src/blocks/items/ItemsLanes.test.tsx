    expect(labels.map(label => label.textContent)).toEqual(props.lanes!.map(lane => lane.label));
    expect(labels.every(label => label.classList.contains("hidden") && label.classList.contains("tablet-lg:block"))).toBe(true);
    const cells = [...list.querySelectorAll<HTMLElement>(":scope > li")];
    expect(cells.map(cell => cell.style.gridColumn)).toEqual(props.items.map((_, i) => String(i + 1)));
    expect(cells.map(cell => cell.style.gridRow)).toEqual(props.items.map((_, i) => String(i % laneCount + 1)));
    expect(list.querySelectorAll("[data-item-transition]")).toHaveLength(count - 1);
    expect(list.querySelectorAll("[data-item-end]")).toHaveLength(1);
    expect(list.querySelectorAll("[data-item-ordinal]")).toHaveLength(count);
    expect(renderToStaticMarkup(<ServerItems {...props} />)).toBe(markup(props));
