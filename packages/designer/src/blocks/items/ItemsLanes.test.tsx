    const special = ["constructor", "__proto__", "toString"];
    expect(() => markup({ ...props, lanes: special.map((id, i) => ({ id, label: `Actor ${i}` })), items: props.items.map((item, i) => ({ ...item, lane: special[i % 3] })) })).not.toThrow();
