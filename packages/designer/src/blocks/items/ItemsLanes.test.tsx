function goldenProps(key: string): { entry: string; props: ItemsProps } {
  const parts = key.split(":");
  const assignment = parts[0] === "assignment";
  const [entry, nested, arrangement, countText, fifth, sixth, seventh] = assignment ? parts.slice(1) : parts;
  const count = Number(countText), id = nested === "true";
  const sequence = assignment ? fifth! : Array.from({ length: count }, (_, i) => i === 1 ? "b" : "a").join("");
  return { entry: entry!, props: {
    arrangement: arrangement === "stacked" ? "stacked" : "columns", columns: arrangement === "stacked" ? undefined : Number(arrangement!.slice(-1)) as 2 | 3,
    order: "connected", ground: assignment ? "base" : fifth as ItemsProps["ground"], treatment: assignment ? "plain" : sixth as ItemsProps["treatment"], end: assignment ? "ends" : seventh as ItemsProps["end"],
    endLabel: slot("Complete", id), className: "caller-lanes", "aria-labelledby": "caller-heading",
    lanes: [{ id: "first", label: slot("First actor", id) }, { id: "second", label: slot("Second actor", id) }],
    items: [...sequence].map((lane, i) => ({ id: `step-${i}`, lane: lane === "a" ? "first" : "second", heading: slot(`Step ${i + 1}`, id), description: slot(`Description ${i + 1}`, id), meta: slot("Context", id) })),
  } };
}
const laneProps = (lanes: number, count: number): ItemsProps => ({
  arrangement: "stacked", order: "connected", "aria-labelledby": "process-heading",
  lanes: Array.from({ length: lanes }, (_, i) => ({ id: `lane-${i}`, label: `Actor ${i + 1}` })),
  items: Array.from({ length: count }, (_, i) => ({ id: `step-${i}`, heading: `Step ${i + 1}`, description: `Support ${i + 1}`, lane: `lane-${i % lanes}` })),
});
const markup = (props: ItemsProps) => renderToStaticMarkup(<Items {...props} />);
