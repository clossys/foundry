    expect(list).toHaveClass("flex", "flex-col", "tablet-lg:grid");
    expect(list).not.toHaveClass("grid");
    expect(frame.style.gridTemplateColumns).toBe(`repeat(${count + 1}, minmax(0, 1fr))`);
    expect(frame.style.gridTemplateRows).toBe(`repeat(${laneCount}, minmax(0, 1fr))`);
    expect(list.style.gridTemplateColumns).toBe(`repeat(${count}, minmax(0, 1fr))`);
    expect(list.style.gridTemplateRows).toBe("subgrid");
