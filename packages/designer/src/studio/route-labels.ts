export type RouteStudioCopyKey = keyof typeof ROUTE_STUDIO_COPY_REFS;

/** Resolve registered labels without storing text, locale or approval policy in Designer. */
export function readRouteStudioLabel(binding: StudioCopyBinding, key: RouteStudioCopyKey, values?: Readonly<Record<string, string | number | boolean>>): string {
  return readStudioCopy(binding, ROUTE_STUDIO_COPY_REFS[key], values);
}

