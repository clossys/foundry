/** Legacy view cells identify catalog data, never untranslated label text. */
export function studioMessageRef(cell: string): { readonly id: string } | undefined {
  if (cell === "designer.scorecard.resolved-count") return STUDIO_MESSAGE_REFS["designer.scorecard.resolvedCount"];
  if (cell === "studio.evaluation.error") return STUDIO_MESSAGE_REFS["admin.designer.error"];
  if (cell.startsWith("studio.ia.item.")) return STUDIO_MESSAGE_REFS[`designer.item.${cell.slice("studio.ia.item.".length)}`];
  for (const prefix of ["studio.ia.board.", "studio.ia.line."]) {
    if (cell.startsWith(prefix)) {
      const parts = cell.slice(prefix.length).split("/");
      return STUDIO_MESSAGE_REFS[`designer.ia.${parts[0]}.${parts.at(-1)}`];
    }
  }
  return STUDIO_MESSAGE_REFS[cell];
}
