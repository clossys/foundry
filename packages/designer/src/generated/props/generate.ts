/**
 * Props types generated from Designer section contracts (foundry-build-0018, ia-target designer.md 9.4.3).
 * One module per live section: `<Name>Copy` from `copy.fields` (dotted keys nest, `[]` becomes an array, `required`
 * drops the `?`), `<Name>Variant` from the closed `members.names` (`axis.value` becomes one optional axis union), and
 * `<Name>Props` binding both. The committed modules under this folder are the build's generated output; tsc compiles
 * them into dist, and `props.test.ts` (not shipped) fails when one drifts from this generator. Regenerate after a build with
 * `node dist/generated/props/write.js src/generated/props` from the package root.
 */
import { createHash } from "node:crypto";

export interface PropsField { key: string; required: boolean; role?: string }
export interface PropsSection {
  id: string;
  contract: { copy?: { fields?: readonly PropsField[] }; members?: { names?: readonly string[] } };
}

type Shape = { fields: Map<string, { required: boolean; array: boolean; child?: Shape; role?: string }> };
const shape = (): Shape => ({ fields: new Map() });

/** `sections.call-to-action` -> `CallToAction`. */
export const pascal = (id: string): string => id.slice(id.indexOf(".") + 1).split(/[^a-zA-Z0-9]+/).filter(Boolean).map(part => part[0]!.toUpperCase() + part.slice(1)).join("");
const prop = (name: string) => /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name);

function build(fields: readonly PropsField[]): Shape {
  const root = shape();
  for (const field of fields) {
    const parts = field.key.split(".");
    let node = root;
    parts.forEach((raw, index) => {
      const array = raw.endsWith("[]");
      const name = array ? raw.slice(0, -2) : raw;
      const leaf = index === parts.length - 1;
      let entry = node.fields.get(name);
      if (!entry) { entry = { required: false, array }; node.fields.set(name, entry); }
      entry.array ||= array;
      if (field.required) entry.required = true;
      if (leaf) entry.role = field.role;
      else node = entry.child ??= shape();
    });
  }
  return root;
}

function render(node: Shape, indent: string): string {
  if (!node.fields.size) return "Record<string, never>";
  const lines = [...node.fields].map(([name, entry]) => {
    const value = entry.child ? render(entry.child, `${indent}  `) : "string";
    const type = entry.array ? (entry.child ? `Array<${value}>` : "string[]") : value;
    const note = entry.role && !entry.child ? ` // ${entry.role}` : "";
    return `${indent}  ${prop(name)}${entry.required ? "" : "?"}: ${type};${note}`;
  });
  return `{\n${lines.join("\n")}\n${indent}}`;
}

/** sha256 of the canonical contract JSON the module was generated from. */
export const contractSha256 = (section: PropsSection): string => createHash("sha256").update(JSON.stringify(section.contract)).digest("hex");

/** Module source for one section. */
export function sectionPropsModule(section: PropsSection): string {
  const name = pascal(section.id);
  const axes = new Map<string, string[]>();
  for (const member of section.contract.members?.names ?? []) {
    const dot = member.indexOf(".");
    const axis = dot < 0 ? "variant" : member.slice(0, dot);
    const value = dot < 0 ? member : member.slice(dot + 1);
    axes.set(axis, [...(axes.get(axis) ?? []), value]);
  }
  const variant = axes.size
    ? `{\n${[...axes].map(([axis, values]) => `  ${prop(axis)}?: ${values.map(value => JSON.stringify(value)).join(" | ")};`).join("\n")}\n}`
    : "Record<string, never>";
  return [
    `// Generated from ${section.id} by src/generated/props/generate.ts; do not edit.`,
    `export const ${name[0]!.toLowerCase()}${name.slice(1)}ContractSha256 = "${contractSha256(section)}";`,
    "",
    `export type ${name}Copy = ${render(build(section.contract.copy?.fields ?? []), "")};`,
    `export type ${name}Variant = ${variant};`,
    `export interface ${name}Props {`,
    `  copy: ${name}Copy;`,
    `  variant?: ${name}Variant;`,
    "}",
    "",
  ].join("\n");
}

/** File name for a section's module. */
export const sectionPropsFile = (id: string): string => `${id}.ts`;

/** Every generated file, keyed by file name, for the given live sections (index last). */
export function generateSectionProps(sections: readonly PropsSection[]): Map<string, string> {
  const files = new Map<string, string>();
  const sorted = [...sections].sort((a, b) => a.id.localeCompare(b.id));
  for (const section of sorted) files.set(sectionPropsFile(section.id), sectionPropsModule(section));
  files.set("index.ts", [
    "// Generated by src/generated/props/generate.ts; do not edit.",
    ...sorted.map(section => `export * from "./${section.id}.js";`),
    "",
  ].join("\n"));
  return files;
}
