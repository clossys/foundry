#!/usr/bin/env node
/**
 * Copies the shared installed-state ledger contract, and a byte-identical
 * copy of the one contract checker implementation, into this package at
 * build time (issue #1178): so @clossys/starter reads
 * `clossys/.state/installed.json` against the same
 * `docs/contracts/installed-ledger.json` that every other reader of a ledger
 * validates against, with no runtime dependency on any other package.
 *
 * Mirrors `packages/strategist/scripts/pack-brief-contract.mjs` -- see that
 * file and `scripts/lib/plan-contracts.mjs`, whose
 * `renderContractSchemaCopy()` this reuses for a byte-identical checker
 * copy -- but packs only the ledger contract, which is self-contained: it
 * refers to no other contract file, so the loader this package gives the
 * checker refuses every name.
 *
 * `src/generated/` is gitignored, like every other packed build output in
 * this repository.
 */
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { renderContractSchemaCopy } from "../../../scripts/lib/plan-contracts.mjs";

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = join(packageRoot, "..", "..");

const LEDGER_CONTRACT_FILE = "installed-ledger.json";
export const LEDGER_CONTRACT_MODULE_PATH = "src/generated/ledger-contract.generated.ts";
export const CONTRACT_SCHEMA_COPY_PATH = "src/generated/contract-schema.generated.ts";

/** The generated data module's source text: the packed ledger contract, parsed and re-serialized. */
function renderLedgerContractModule() {
  const contract = JSON.parse(readFileSync(join(repoRoot, "docs", "contracts", LEDGER_CONTRACT_FILE), "utf8"));
  return `// AUTO-GENERATED by this package's build-time packer (issue #1178).
// Do not edit by hand -- edits are overwritten on the next \`npm run build\`.
// Source of truth: the shared installed-state ledger contract in this
// package's source repository (not shipped in this package). Every package
// that validates a ledger packs this same contract.

/** The shared installed-state ledger contract (${LEDGER_CONTRACT_FILE}) this package validates against. */
export const LEDGER_CONTRACT: Readonly<Record<string, unknown>> = ${JSON.stringify(contract, null, 2)};
`;
}

const generatedDir = join(packageRoot, "src", "generated");
if (existsSync(generatedDir)) rmSync(generatedDir, { recursive: true, force: true });
mkdirSync(generatedDir, { recursive: true });
writeFileSync(join(packageRoot, LEDGER_CONTRACT_MODULE_PATH), renderLedgerContractModule());
writeFileSync(join(packageRoot, CONTRACT_SCHEMA_COPY_PATH), renderContractSchemaCopy(repoRoot));
console.log("pack-ledger-contract: wrote the installed-ledger contract and the contract checker copy into src/generated/");
