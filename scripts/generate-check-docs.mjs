#!/usr/bin/env node
// Repository tooling only; installed consumers read the generated companion.
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const packageRoot = new URL("../packages/designer/", import.meta.url);
export const checkDocsPath = new URL("skill/check-codes.md", packageRoot);

export async function checkData() {
  const path = new URL("src/catalog-core/check-guidance.ts", packageRoot);
  const source = readFileSync(path, "utf8");
  const parsed = ts.createSourceFile("check-guidance.ts", source, ts.ScriptTarget.ES2022, true);
  if (parsed.statements.some(s => ts.isImportEqualsDeclaration(s) || ts.isImportDeclaration(s) && !s.importClause?.isTypeOnly)) throw Error("Check guidance may import types only.");
  const { outputText } = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } });
  const data = await import(`data:text/javascript;base64,${Buffer.from(outputText).toString("base64")}`);
  // Resolve the real public union, including template-literal and imported types.
  const typesPath = fileURLToPath(new URL("src/catalog-core/types.ts", packageRoot));
  const program = ts.createProgram([typesPath], { target: ts.ScriptTarget.ES2022, skipLibCheck: true, types: [] });
  const types = program.getSourceFile(typesPath), checker = program.getTypeChecker();
  const finding = types.statements.find(s => ts.isInterfaceDeclaration(s) && s.name.text === "Finding");
  const property = finding?.members.find(s => s.name?.getText(types) === "code");
  if (!property?.type) throw Error("Finding.code is missing.");
  const union = checker.getTypeAtLocation(property.type);
  const members = union.isUnion() ? union.types : [union];
  if (members.some(t => !t.isStringLiteral())) throw Error("Finding.code must be a finite string union.");
  const expected = members.map(t => t.value).sort();
  if (JSON.stringify([...data.CHECK_CODES].sort()) !== JSON.stringify(expected)) throw Error("Check guidance must cover every Finding.code exactly once.");
  return data;
}

async function dogfoodGuidance() {
  const source = readFileSync(new URL("src/catalog-core/dogfood.ts", packageRoot), "utf8");
  const parsed = ts.createSourceFile("dogfood.ts", source, ts.ScriptTarget.ES2022, true);
  const statement = parsed.statements.find(node => ts.isVariableStatement(node) && node.declarationList.declarations.length === 1 && node.declarationList.declarations[0].name.getText(parsed) === "DOGFOOD_GUIDANCE");
  if (!statement) throw Error("Dogfood guidance is missing.");
  // Evaluate only the self-contained literal declaration, never the scanner or its imports.
  const literal = ts.createPrinter().printNode(ts.EmitHint.Unspecified, statement, parsed);
  const { outputText } = ts.transpileModule(literal, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } });
  return (await import(`data:text/javascript;base64,${Buffer.from(outputText).toString("base64")}`)).DOGFOOD_GUIDANCE;
}

export async function generateCheckDocs() {
  const { CHECK_CODES, CHECK_GUIDANCE } = await checkData();
  const lines = ["# Library check codes", "", "<!-- Generated by scripts/generate-check-docs.mjs (repository tooling that does not ship). Edit src/catalog-core/check-guidance.ts or src/catalog-core/dogfood.ts and regenerate. -->", "",
    "Read each finding's actual severity, subject and message. An error fails the check; a notice or warning is reported without making the engine verdict fail. A notice is not proof that an unmeasured check passed.", "",
    "Fix operations below are proposals from the current ChangeSet vocabulary. They never run automatically and do not grant permission to write. Some corrections require catalog ownership or external evidence rather than any operation. The chooser never authors values; authored values must come from the consumer.", "",
    "Only currently typed codes appear here. Component, section and frame checks are unavailable until implemented; future K, CC, SK and FK codes need runtime guidance when added to Finding.code."];
  for (const code of CHECK_CODES) {
    const row = CHECK_GUIDANCE[code];
    lines.push("", `## ${code}`, "", row.meaning, "",
      `- Severity: ${row.severities.length ? row.severities.join(" or ") : "reserved; no current emitted severity"}.`,
      `- Typical cause: ${row.typicalCause}`,
      `- Proposed fix ops: ${row.fixOps.length ? row.fixOps.map(op => `\`${op}\``).join(", ") : "none"}.`,
      `- Next action: ${row.fix}`);
  }
  lines.push("", "This reference is generated from the exhaustive runtime guidance record. Repository maintainers regenerate with `node scripts/generate-check-docs.mjs` and verify with `node scripts/check-check-docs.mjs`; those scripts do not ship in the installed package.", "");
  lines.push("## Derived surface dogfood", "", "DF codes belong to DogfoodFinding, independently of the library engine's Finding codes. These static findings do not certify runtime behavior. Dynamic classes, styles and spreads remain unresolved findings. Structural wrappers may have no look of their own; token utilities still require declared reads.");
  for (const [code, row] of Object.entries(await dogfoodGuidance())) lines.push("", `## ${code}`, "", row.meaning, "", `- Next action: ${row.fix}`);
  lines.push("");
  return lines.join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  writeFileSync(checkDocsPath, await generateCheckDocs());
  console.log("Check code reference generated from runtime guidance.");
}
