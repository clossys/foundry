/**
 * The shared plan, brief and inventory contracts (issues #1475, #1334 and #1179),
 * packed into each package that validates against them.
 *
 * `docs/contracts/advisor-plan.json`, `engagement-brief.json` and
 * `engagement-context.json` are the one definition of the plan record and
 * the engagement brief; `repository-inventory.json` is the one definition
 * of a hub's repository inventory. `@clossys/advisor` owns the plan and
 * brief shapes and checks the repository ids it offers against the
 * inventory contract; `@clossys/launcher` reads all four, and neither
 * package depends on the other at runtime. So each
 * package's own build step writes the same generated module into its
 * `src/generated/`: the packed contracts as plain data, with no file I/O at
 * runtime. Both packages render it through this one function, so their
 * copies of those three are byte-identical by construction.
 *
 * `@clossys/advisor` also packs `registry-snapshot.json` (issue #1178), the
 * contract of the registry snapshot it resolves a plan's exact package acts
 * from, and the scope and registry from this repository's
 * `package-scope.json`, so it can name packages and check a snapshot's
 * registry without hardcoding either.
 *
 * The checker that interprets those contracts lives once, in
 * `packages/advisor/src/contract-schema.ts`. Launcher's build writes a
 * byte-identical copy of it, under a generated-file header, because
 * Launcher cannot import Advisor.
 *
 * Both generated directories are gitignored, like every other packed
 * build output here.
 */
import { readFileSync } from "node:fs";
import { join } from "node:path";

/** The contracts packed, in this order. `engagement-brief.json` refers to `engagement-context.json` by file name. */
export const PLAN_CONTRACT_FILES = ["advisor-plan.json", "engagement-brief.json", "engagement-context.json", "repository-inventory.json"];

/** The contracts `@clossys/advisor` packs: the shared ones, then the registry snapshot it resolves packages from. */
export const ADVISOR_PLAN_CONTRACT_FILES = [...PLAN_CONTRACT_FILES, "registry-snapshot.json"];

/** Package-relative paths of the generated modules. */
export const PLAN_CONTRACTS_MODULE_PATH = "src/generated/plan-contracts.generated.ts";
export const CONTRACT_SCHEMA_COPY_PATH = "src/generated/contract-schema.generated.ts";
export const PACKAGE_SCOPE_MODULE_PATH = "src/generated/package-scope.generated.ts";

/** Repository-relative path of the one checker implementation. */
export const CANONICAL_CONTRACT_SCHEMA_PATH = "packages/advisor/src/contract-schema.ts";

const DATA_BANNER = `// AUTO-GENERATED by this package's build-time packer (issue #1475).
// Do not edit by hand -- edits are overwritten on the next \`npm run build\`.
// Source of truth: the shared plan, brief and inventory contracts in this
// package's source repository (not shipped in this package). Every package
// that validates a plan, a brief or an inventory packs this same module.
`;

const COPY_BANNER = `// AUTO-GENERATED by this package's build-time packer (issue #1475).
// Do not edit by hand -- edits are overwritten on the next \`npm run build\`.
// A byte-identical copy of the contract checker in @clossys/advisor (its
// source file is not shipped in this package), the one implementation, for a
// package that has no runtime dependency on @clossys/advisor.
`;

const SCOPE_BANNER = `// AUTO-GENERATED by this package's build-time packer (issue #1178).
// Do not edit by hand -- edits are overwritten on the next \`npm run build\`.
// Source of truth: the one file in this package's source repository that sets
// the publishing scope and registry (not shipped in this package).
`;

/** The generated data module's source text: every packed contract, parsed and re-serialized. */
export function renderPlanContractsModule(repoRoot, files = PLAN_CONTRACT_FILES) {
  const entries = files.map((name) => {
    const contract = JSON.parse(readFileSync(join(repoRoot, "docs", "contracts", name), "utf8"));
    return `  ${JSON.stringify(name)}: ${JSON.stringify(contract, null, 2).replace(/\n/g, "\n  ")},`;
  });
  return `${DATA_BANNER}
/** The shared plan, brief and inventory contracts, keyed by their file name in docs/contracts/. */
export const PLAN_CONTRACTS: Readonly<Record<string, Readonly<Record<string, unknown>>>> = {
${entries.join("\n")}
};
`;
}

/** The generated copy of the one checker implementation, for a package that cannot import it. */
export function renderContractSchemaCopy(repoRoot) {
  return `${COPY_BANNER}\n${readFileSync(join(repoRoot, ...CANONICAL_CONTRACT_SCHEMA_PATH.split("/")), "utf8")}`;
}

const SCOPE_PATTERN = /^@[a-z0-9][a-z0-9._-]*$/;
const REGISTRY_PATTERN = /^https:\/\/[a-z0-9](?:[a-z0-9.-]*[a-z0-9])?(?::[0-9]{1,5})?$/;

/**
 * The generated scope module's source text: only `scope` and `registry`
 * from `package-scope.json`, checked before they are packed, so a malformed
 * value fails the build rather than ship.
 */
export function renderPackageScopeModule(repoRoot) {
  const { scope, registry } = JSON.parse(readFileSync(join(repoRoot, "package-scope.json"), "utf8"));
  if (typeof scope !== "string" || !SCOPE_PATTERN.test(scope)) throw new Error("package-scope.json: scope must be a lowercase npm scope such as @scope");
  if (typeof registry !== "string" || !REGISTRY_PATTERN.test(registry)) throw new Error("package-scope.json: registry must be an https origin with no path and no trailing slash");
  return `${SCOPE_BANNER}
/** The publishing scope and the registry packages are published to and read from. */
export const PACKAGE_SCOPE: { readonly scope: string; readonly registry: string } = ${JSON.stringify({ scope, registry }, null, 2)};
`;
}
